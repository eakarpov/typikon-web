// Единственное место, где записан адрес сайта.
//
// До этого он стоял в коде 120 раз: в метаданных страниц, в описаниях ручек API,
// в манифесте выгрузки, в карте сайта, в robots.txt, в подписных календарях и в
// заголовках, которыми мы представляемся чужим серверам. Переезд на другой домен
// означал бы правку в ста двадцати местах, из которых половина не всплыла бы ни
// при сборке, ни при тестах — только у читателя.
//
// Простой константой, а не переменной окружения: адрес нужен и на сервере, и в
// браузере (сборщик виджета показывает готовую строку для чужого сайта), а в
// клиентскую сборку Next вносит только NEXT_PUBLIC_*. Разводить два способа
// задать одно и то же — заводить рассинхрон на ровном месте. Переезд правится
// здесь одной строкой.

export const SITE_URL = "https://www.typikon.su";

/** Полное имя хоста, как его присылает браузер: с www. */
export const SITE_HOST_FULL = SITE_URL.replace(/^https?:\/\//, "");

/**
 * Как домен пишется в тексте: без протокола и без www. Выводится из SITE_URL, а
 * не записывается вторым литералом: два литерала однажды разойдутся, и разойдутся
 * молча — в письме или в указании источника, где этого никто не проверяет.
 */
export const SITE_HOST = SITE_HOST_FULL.replace(/^www\./, "");

/**
 * Тот же сайт без www. Форма не декоративная: она зарегистрирована в консоли
 * приложения VK как адрес возврата (там сверяется до знака) и приходит в
 * заголовке Origin у части запросов, поэтому считается своей.
 */
export const SITE_URL_NAKED = `https://${SITE_HOST}`;

/** Куда VK возвращает после входа — ровно как записано у него в настройках. */
export const VK_REDIRECT_URL = `${SITE_URL_NAKED}/login`;

/**
 * Пространство имён для UID событий в подписных календарях — и оно ЗАМОРОЖЕНО.
 *
 * UID это не адрес, а имя: по нему календарь узнаёт событие, которое у него уже
 * есть. Сменишь — и у каждого подписчика лента задвоится рядом со старой, потому
 * что все события окажутся новыми. Поэтому UID не должен зависеть от того, где
 * сайт живёт сегодня, и SITE_URL сюда не подставляется.
 *
 * Записан будущий домен, а не нынешний: переезд на typikon.info назначен до конца
 * 2026 года, ленты заведены несколько дней назад и подписчиков у них считанные
 * единицы. Сменить имена сейчас — один раз побеспокоить их, сменить после
 * переезда — побеспокоить всех, а оставить как есть — навсегда развести имена с
 * адресом. После переезда эта строка не меняется больше никогда.
 */
export const ICS_UID_DOMAIN = "typikon.info";

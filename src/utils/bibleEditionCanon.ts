import { BIBLE_CANON } from "@/utils/bibleCanon";

/**
 * Канон издания — что его традиция вообще ДЕРЖИТ Писанием.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ОБЪЁМА. Это разные оси, и валить их в одну значило бы врать
 * в обе стороны. Объём (@/utils/bibleScope) говорит, сколько своего канона несёт
 * данное издание: Четвероевангелие — только Евангелие, и это свойство книги.
 * Канон говорит, чего у традиции нет вовсе: 3 Маккавейской в латинском каноне
 * не было никогда, и полнее латинская Библия от этого не станет.
 *
 * Пример, на котором видно, что осей две: латинское Четвероевангелие не имело бы
 * ни Деяний (вне объёма), ни 3 Маккавейской (вне канона) — и это две разные
 * причины, а не одна.
 *
 * ЭТАЛОН — САМЫЙ ШИРОКИЙ. Наш канон славянский, и он держит больше всех: и
 * 3 Маккавейскую, и обе поздние Ездры, и 151-й псалом. Поэтому канон издания
 * описывается СПИСКОМ ОТСУТСТВУЮЩЕГО, а не своим перечнем книг: так видно ровно
 * то, что отличает, и новая книга канона не требует править каждый список.
 *
 * ЧЕГО ЭТО ПОЛЕ НЕ ВЫРАЖАЕТ. Оно книжное, а разница бывает и мельче: 151-го
 * псалма в латинской нет, но псалом — глава, а не книга. Такие места остаются
 * приговорами главам в @/lib/bible/mappings, и подменять одно другим не нужно.
 *
 * ОБЪЯВЛЯЕТСЯ ТОЛЬКО ДОКАЗАННОЕ. Румынская 1688 в нашем составе без 2 Ездры, но
 * переведена она с Септуагинты, где Ἔσδρας Α есть, — значит это скорее наша
 * недоделка, чем свойство канона. Пока не проверено, канон ей не объявляется, и
 * книга честно значится недостающей.
 */
export interface BibleEditionCanon {
    id: string;
    title: string;
    /** Книги эталона, которых этот канон не держит. */
    absent: string[];
}

export const BIBLE_EDITION_CANONS: BibleEditionCanon[] = [
    {
        id: "sla",
        title: "славянский",
        // Эталон: держит всё, что держим мы.
        absent: [],
    },
    {
        id: "grc-lxx",
        title: "греческий (Септуагинта)",
        // 3 Ездры (лат. IV Esdrae) по-гречески не существовало: книга дошла на
        // латыни, сирийском, эфиопском и армянском, греческого текста нет.
        // Пустая колонка тут — честный итог, а не дыра, которую надо заполнить.
        absent: ["3-ezdry"],
    },
    {
        id: "la-vulgata",
        title: "латинский (Вульгата)",
        // 3 Маккавейская есть у Семидесяти и в славянской, но в латинский канон
        // не входила никогда — ни до Тридентского собора, ни после.
        absent: ["3-makkaveyskaya"],
    },
];

export const DEFAULT_BIBLE_EDITION_CANON = "sla";

export const bibleEditionCanonTitle = (canon: string | null | undefined): string =>
    BIBLE_EDITION_CANONS.find((entry) => entry.id === canon)?.title
    ?? BIBLE_EDITION_CANONS.find((entry) => entry.id === DEFAULT_BIBLE_EDITION_CANON)!.title;

/**
 * Книга вне канона издания: её отсутствие — свойство традиции, а не недоделка.
 *
 * Незнакомый канон считаем эталонным, а не пустым: приняв незнакомое за «ничего
 * не держит», сверка молча перестала бы искать дыры во всём издании.
 */
export const outsideBibleEditionCanon = (canon: string | null | undefined, bookId: string): boolean => {
    const entry = BIBLE_EDITION_CANONS.find((candidate) => candidate.id === canon);
    return entry ? entry.absent.includes(bookId) : false;
};

/** Книги эталона, которых у канона нет, — с названиями, для отчёта. */
export const absentFromCanon = (canon: string | null | undefined) => {
    const entry = BIBLE_EDITION_CANONS.find((candidate) => candidate.id === canon);
    if (!entry || !entry.absent.length) return [];
    return entry.absent.map((id) => BIBLE_CANON.find((book) => book.id === id)?.name ?? id);
};

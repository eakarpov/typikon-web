// Книги, которые издания печатают, а славянский канон не держит.
//
// ЗАЧЕМ ОТДЕЛЬНЫМ СПИСКОМ, А НЕ СТРОКАМИ В bibleCanon. Идентификаторы канона —
// это адреса: по ним резолвятся 1067 зачал и размечены сноски. Заведи мы Еноха
// книгой канона, и `pericopes.bookSlug` начал бы принимать «enokha», а чтение
// на службе — резолвиться в него. Канон должен остаться списком того, что
// Церковь читает; всё остальное издание печатает, но уставом оно не названо.
//
// ЧТО СЮДА ПОПАДАЕТ. Два разных случая, и различать их важно:
//
//   1. Книги, которым в каноне нет соответствия вовсе — Оды, Псалмы Соломона,
//      4 Маккавейская, Енох, пролог Сираха.
//   2. ВТОРЫЕ ИЗВОДЫ книг, которые в каноне есть. Свит печатает Даниила,
//      Сусанну и Вила дважды — переводом LXX и Феодотионовым, — и Товита в двух
//      изводах. Каноническое место занимает тот, с которого переведена
//      славянская (Феодотион, ватиканский Товит), а второй получает свой адрес
//      здесь. Иначе два разных текста претендовали бы на один canonRef, и
//      параллельный вид молча показал бы который-нибудь один.
//
// Стихи этих книг лежат в тех же bible_verses и сводятся тем же canonRef —
// просто их canonId не встречается ни в одном другом издании, поэтому колонка
// рядом пуста. Это честно: у славянской Библии Еноха и правда нет.
export interface AppendixBook {
    id: string;
    name: string;
    /** Короткое имя для навигации; сокращений из разметки сносок у них нет. */
    abbr: string;
    /** Откуда книга взялась и почему стоит вне канона — показывается в оглавлении. */
    note: string;
}


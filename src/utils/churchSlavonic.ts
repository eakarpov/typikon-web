// Нормализация церковнославянского текста для сопоставления: снимает ударения и надстрочные
// знаки (звательце, титло), приводит ЦС-графику к гражданской (ѣ→е, ꙋ→у, ѧ→я, ѡ→о, і→и, ѵ→и,
// ꙗ→я, ѳ→ф, ѕ→з), ё→е, регистр. Нужна там, где сравнивается написанное по-разному одно и то же
// слово: 2925 текстов набраны гражданкой с ударениями, ещё 305 — собственно ЦС-графикой.
//
// Буквы записаны кодами, а не начертанием, и это не педантизм. Половину из них глазом не
// отличить от гражданских соседок (і от и, ѻ от о, ᲂ от о) и друг от друга: ѡ от ѽ, ѧ от ѩ.
// Опечатка в такой таблице ничем себя не выдаёт — просто одно слово перестаёт находиться, —
// и при наборе таблицы руками она немедленно и случилась: ѡ (U+0461) обернулась ѽ (U+047D),
// и «і҆ѡа́нна» сложилась в «иѡанна» вместо «иоанна». Правя таблицу, сверяйся с кодами.
const CS_LETTER_MAP: Record<string, string> = {
    "\u0463": "е", "\ua64b": "у", "\u0479": "у", "\u0467": "я", "\u0469": "я", "\ua657": "я",
    "\u0461": "о", "\u047f": "от", "\u047b": "о", "\u0456": "и", "\u0457": "и", "\u0475": "и",
    "\u0454": "е", "\u0455": "з", "\u0473": "ф", "\u046b": "у", "\u046f": "кс", "\u0471": "пс",
    // U+1C82, узкое о: само по себе — просто «о»; в диграфе разбирается раньше.
    "\u1c82": "о",
};

// «ᲂу» — не две буквы, а одна: диграф «ук» (U+1C82 + у). Посимвольно он сложился бы в «оу»
// и не сошёлся бы с гражданским «у», поэтому разбирается первым. В корпусе так набраны
// 90 текстов из 3403, и до этого поиск не находил их вовсе.
const UK_DIGRAPH = /\u1c82\u0443/g;

export const normalizeChurchSlavonic = (text: string) =>
    text
        .normalize("NFD")
        // U+0300-U+036F — ударения; U+0483-U+0489 — титло, звательце и прочие ЦС-надстрочные.
        .replace(/[\u0300-\u036f\u0483-\u0489]/g, "")
        .toLowerCase()
        .replace(/\u0451/g, "е")
        .replace(UK_DIGRAPH, "у")
        .replace(/[\u0463\ua64b\u0479\u0467\u0469\ua657\u0461\u047f\u047b\u0456\u0457\u0475\u0454\u0455\u0473\u046b\u046f\u0471\u1c82]/g, (ch) => CS_LETTER_MAP[ch] ?? ch);

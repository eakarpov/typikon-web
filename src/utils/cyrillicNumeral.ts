/**
 * Кириллическая цифирь: «ѳ҃і» — 19, «м҃д» — 44, «р҃кѳ» — 129.
 *
 * Нужна не для красоты: румынский набор 1688 года печатает номера стихов
 * цифирью, и там, где сборщик текста её не опознал, стих слипся с предыдущим —
 * номер остался стоять посреди строки. Чтобы разделить их обратно, число надо
 * уметь прочесть.
 *
 * СУММА, А НЕ ПОЗИЦИЯ. В цифири единицы второго десятка пишутся наоборот
 * («а҃і» — 11, единица перед десяткой), а прочие в обычном порядке («к҃а» — 21).
 * Простая сумма значений букв верна и там и там, и позиционный разбор тут
 * только добавил бы способов ошибиться.
 *
 * ТИТЛО ОБЯЗАТЕЛЬНО. Без него «ми» — предлог или слог, а не число 48. Требовать
 * титла — единственное, что отличает цифирь от обычного слова, и без этого
 * условия починка резала бы текст по живому.
 */
import { csNumeral } from "@/lib/csEncoding/numerals";

/** Число из цифири; null — если это не цифирь или в ней нет пометы. */
export const cyrillicNumeral = (token: string): number | null =>
    // Строго: чужая буква значит, что это не число, и резать по нему текст нельзя.
    // Таблица значений — одна на проект, в @/lib/csEncoding/numerals.
    csNumeral(token, { strict: true });

/**
 * Ищет в тексте цифирь, равную ожидаемому номеру, и делит по ней надвое.
 * Возвращает null, если такой цифири нет, — молча резать нельзя.
 */
export const splitAtNumeral = (
    text: string, expected: number,
): { before: string; after: string } | null => {
    // Цифирь может стоять слитно со следующим словом («р҃кѳМинꙋна́те»), поэтому
    // ищем её как последовательность цифирных букв с титлом, а не как слово.
    const re = /\.?\s*([а-яєѕіѡѣѧѯѱѳᲂ҃-҉]+)/gu;
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
        // Отрезаем от найденного куска самое длинное начало, которое читается
        // как нужное число: дальше идёт уже текст стиха.
        for (let len = Math.min(m[1].length, 8); len >= 1; len--) {
            const head = m[1].slice(0, len);
            if (cyrillicNumeral(head) !== expected) continue;
            const before = text.slice(0, m.index).replace(/[\s.]+$/, "");
            const after = text.slice(m.index + (m[0].length - m[1].length) + len).trim();
            if (!before || !after) return null;
            return { before, after };
        }
    }
    return null;
};

// Реестр источников сведений о храмах — и, главное, что с каждым можно делать.
//
// ЗАЧЕМ РЕЕСТР. Источников набралось несколько, и условия у них РАЗНЫЕ. Wikidata
// отдана в общественное достояние, OSM требует указания авторства, а частные
// своды — sobory.ru, temples.ru, days.pravoslavie.ru, епархиальные каталоги —
// не отдают ничего: там своя работа своих людей. Держать это знание в головах
// нельзя: через полгода никто не вспомнит, откуда что взято и что можно
// показывать.
//
// ПОЧЕМУ ЧАСТНЫЕ ВСЁ-ТАКИ НУЖНЫ. У них есть то, чего нет ни в одном открытом
// своде: ПРИДЕЛЫ. «Храм святителя Николая (Воскресения Христова) в Ржавках»,
// «Храм бессребреников Космы и Дамиана (Благовещения) в Шубине» — второй
// престол выписан прямо в заголовке. Из открытых данных такое не выводится:
// имя в OSM и Wikidata называет один престол, и то не всегда.
//
// ЧТО МЫ С НИМИ ДЕЛАЕМ. Три правила, и разница между ними существенная:
//
//   import — везём в каталог целиком (открытая лицензия это позволяет);
//   link   — не везём ничего, даём читателю ссылку на их страницу;
//   verify — сверяем ПООДИНОЧКЕ, руками, когда приход уточняет свой храм.
//
// Отдельный факт («у этого храма придел Благовещения») ничьей собственностью
// не является, а вот свод целиком — чужой труд, и выкачивать его нельзя.
// Разница проходит по объёму: сверить свой приход — одно, забрать сорок тысяч
// записей — другое. Захочется большего — это разговор с владельцами свода, а
// не задача для скрипта.

export type SourcePolicy = "import" | "link" | "verify";

export interface TempleSource {
    key: string;
    label: string;
    url: string;
    /** Условия, как их объявляет сам источник. */
    license: string;
    policy: SourcePolicy;
    /** Требуется ли называть источник рядом с данными. */
    attribution: boolean;
    /** Чем этот источник ценен и чего в нём нет. */
    note: string;
    /** Поиск по названию храма — для правила «link». */
    search?: (name: string) => string;
}


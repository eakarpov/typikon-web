export const sourceByKey = (key: string): TempleSource | undefined =>
    TEMPLE_SOURCES.find((s) => s.key === key);

/** Куда отослать читателя за тем, чего у нас нет: приделами и историей здания. */
export const lookupLinks = (name: string) =>
    TEMPLE_SOURCES.filter((s) => s.policy === "link" && s.search)
        .map((s) => ({ label: s.label, href: s.search!(name) }));

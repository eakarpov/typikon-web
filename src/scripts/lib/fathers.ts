/**
 * Названия книг -> их _id в коллекции books. Каждое название должно найтись
 * ровно один раз: не нашлось — кто-то переименовал книгу или опечатался в
 * списке; нашлось несколько — названия перестали различать книги. Оба случая
 * останавливают сборку, потому что молчание здесь означало бы тихую потерю
 * текста из записи архива.
 */
export const fathersBookIds = async (db: {
    collection: (name: string) => {
        find: (filter: Record<string, unknown>) => {
            toArray: () => Promise<Record<string, any>[]>;
        };
    };
}): Promise<Set<string>> => {
    const books = await db.collection("books").find({}).toArray();
    const byName = new Map<string, string[]>();
    for (const book of books) {
        const list = byName.get(book.name) ?? [];
        list.push(String(book._id));
        byName.set(book.name, list);
    }

    const ids = new Set<string>();
    const problems: string[] = [];
    for (const name of FATHERS_BOOK_NAMES) {
        const matches = byName.get(name) ?? [];
        if (matches.length !== 1) {
            problems.push(`«${name}» — совпадений: ${matches.length}`);
            continue;
        }
        ids.add(matches[0]);
    }
    if (problems.length) {
        throw new Error(
            "Список отеческих книг не сошёлся с коллекцией books:\n  "
            + problems.join("\n  "),
        );
    }
    return ids;
};

// Какие книги собрания считаются святоотеческими и уставными чтениями.
//
// Третья запись архива (наряду с «корпус + Библия» и «храмы») выкладывает именно
// эти книги отдельным срезом: чтобы на Шестоднев, Златоустника, Паренесис,
// Маргарит, Толкования, торжественники, синаксари и жития можно было ссылаться
// своим DOI, а не DOI всего корпуса. Флага «отеческая книга» в данных нет —
// разбиение по правам здесь не требуется (всё под CC BY 4.0), поэтому критерий —
// просто согласованный список, как его подтвердил владелец.
//
// Книги опознаются по ТОЧНОМУ названию, а не по ObjectId: ObjectId не читается
// в diff'ах и не говорит, что легло в выгрузку. Название переименуют рано или
// поздно — и резолвер ниже упадёт громко, а текст не потеряется из выгрузки
// молча. Список не выводится из привязок к дням намеренно: Маргарит, Шестоднев
// и Толкования по замыслу входят в уставные чтения, хотя к дням пока почти
// не привязаны — состав книг определяется замыслом, а не текущим состоянием
// разметки.


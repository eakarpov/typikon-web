// Слова имени, из которых получаются хэштеги поста. Вынесено из buildPost
// отдельным модулем: правило проверяется тестами, а buildPost тянет за собой
// и базу, и сеть.

/**
 * Служебные слова, которые не должны становиться хэштегами.
 *
 * «Пётр и Павел» давало #Пётр #и #Павел: союз уезжал в канал отдельным хэштегом
 * и ни в каком поиске не помогал.
 *
 * Список, а не отсечение по длине: короткое слово короткому рознь — мученица Ия
 * носит имя из двух букв, и правило «короче трёх букв — выбросить» отняло бы у
 * неё имя. Предлоги здесь тоже перечислены: они встречаются в именах вида
 * «Иоанн от Скита», и хэштег из предлога так же бесполезен, как из союза.
 */
const SERVICE_WORDS = new Set([
    "и", "а", "но", "да", "же", "или", "либо",
    "в", "во", "на", "с", "со", "из", "от", "до", "к", "ко", "по", "за",
    "о", "об", "обо", "при", "про", "над", "под", "для", "у",
]);

/**
 * Имя разбивается на отдельные хэштеги по словам («Стефан Первомученик» ->
 * #Стефан #Первомученик): по одному слову искать вероятнее, чем по слитному
 * «#СтефанПервомученик». Чисто цифровые части (например «9» из «9 мучеников
 * Пергийских») хэштегами не становятся — по ним не ищут.
 */
export const nameHashtagWords = (name?: string | null): string[] =>
    (name || "")
        .split(/\s+/)
        .filter((word) => /[А-Яа-яЁё]/.test(word))
        .filter((word) => !SERVICE_WORDS.has(
            word.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^а-яё]/g, ""),
        ));

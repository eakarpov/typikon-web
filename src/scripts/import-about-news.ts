const aliasOf = (release: Release) =>
    release.alias ?? `versiya-${release.version.replace(/\./g, "-")}`;

const summaryOf = (release: Release) => {
    if (release.text) return release.text.split("\n")[0];

    return release.items.length > 1
        ? `${release.items[0]} и ещё ${release.items.length - 1}`
        : release.items[0];
};

const bodyOf = (release: Release) => {
    if (release.text) return release.text;

    const list = release.items.map((item) => `- ${item}`).join("\n");

    if (!release.fromAbout) return list;

    return `${list}\n\n_Перенесено из списка версий на странице «О проекте»` +
        (release.approxDate
            ? "; точной даты выпуска в истории нет, взят день ближайшего следующего._"
            : "._");
};

async function main() {
    const client = await clientPromise;
    const posts = client.db(NEWS_DB).collection(NEWS_COLLECTION);

    const existing = new Set(
        (await posts.find({}, { projection: { alias: 1 } }).toArray()).map((post: any) => post.alias),
    );

    const fresh = RELEASES.filter((release) => !existing.has(aliasOf(release)));

    console.log(`Версий в списке: ${RELEASES.length}, из них ещё не перенесено: ${fresh.length}`);
    for (const release of fresh) {
        console.log(`  ${release.date}${release.approxDate ? "*" : " "}  ${aliasOf(release)}  (${release.text ? "свободный текст" : `${release.items.length} п.`})`);
    }

    if (!fresh.length) {
        console.log("Переносить нечего.");
        return;
    }

    if (!APPLY) {
        console.log("\n* — дата по соседнему выпуску.");
        console.log("Холостой прогон — ничего не создано. Повторите с --apply.");
        return;
    }

    await posts.insertMany(fresh.map((release) => {
        // Время суток у старых выпусков неизвестно — ставим полдень, чтобы запись не
        // уехала в соседние сутки при показе в местном часовом поясе. Явное время нужно
        // там, где в один день пришлось несколько записей: лента сортируется по нему, и
        // при равенстве порядок оказался бы случайным.
        const at = new Date(`${release.date}T${release.time ?? "12:00"}:00.000Z`);

        return {
            alias: aliasOf(release),
            title: release.title ?? `Версия ${release.version}`,
            summary: summaryOf(release),
            body: bodyOf(release),
            type: release.type ?? ("update" as const),
            version: release.version,
            status: "published" as const,
            publishedAt: at,
            createdAt: at,
            updatedAt: at,
        };
    }) as any);

    console.log(`\nПеренесено записей: ${fresh.length}.`);
    await revalidateNews();
}

main().then(() => process.exit(0)).catch((e) => {
    console.error(e);
    process.exit(1);
});

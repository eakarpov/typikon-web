// Список версий вёлся руками в JSX на странице «О проекте» и отстал: последняя запись
// была 4.2, тогда как в репозитории уже 5.2. Ленте он подходит лучше: у каждой записи
// свой адрес, она уходит в RSS и в /api/v2/news, и о новой узнают, а не находят
// случайно.
//
// Записи 5.1 и 5.2 на странице «О проекте» не значились — их состав взят из доски
// задач, поэтому пометки о переносе у них нет.
//
// Даты восстановлены по истории репозитория: выпуски отмечены коммитами, названными
// самой версией («1.7.0», «2.4»), и берётся последний такой коммит — у версии их
// бывает несколько («4.0 beta-42», потом «4.0»). Альфы, беты и версии приложения
// отброшены. Пяти версиям (4.2, 4.1, 1.8.2, 1.2.3, 0.1.0) своего коммита не нашлось:
// им поставлен день ближайшего следующего выпуска (для 0.1.0 — начало репозитория),
// и в самой записи об этом сказано. Порядок дат проверен: он совпадает с порядком
// версий в старом списке.
//
// Скрипт идемпотентный: записи заводятся по постоянному адресу versiya-X-Y-Z, и
// повторный прогон пропускает уже перенесённое.
//
// Запуск:
//   npx tsx src/scripts/import-about-news.ts           # что будет создано
//   npx tsx src/scripts/import-about-news.ts --apply   # перенести

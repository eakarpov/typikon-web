// Подписи нужны окну ввода, то есть клиенту, а разбор ходит в указатель
// зачинов, то есть тянет за собою better-sqlite3. Импортируй клиент разбор
// целиком — и в браузер уехал бы драйвер SQLite, где он умирает на promisify.
// В этом репозитории на этом уже обжигались (см. предупреждения в Filters.tsx
// у зачинов и акафистов), и правило одно: через границу клиента ходят только
// типы да чистые словари.

export type LineFlag =
    /** В кириллическом слове стоит латинская буква — или наоборот. */
    | "mixed-script"
    /** Ударений нет вовсе: строку не прочесть вслух и не спеть. */
    | "no-accents"
    /** Нет разметки колен: напев на такую строку не ляжет. */
    | "no-colons"
    /** Строка повторяется в присланном тексте. */
    | "repeated"
    /** Строка короче трёх слов: по ней ничего не найти. */
    | "too-short";


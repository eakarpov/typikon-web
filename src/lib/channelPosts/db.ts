import clientPromise from "@/lib/mongodb";

// ГДЕ ЛЕЖАТ ПОСТЫ КАНАЛА — и почему не там же, где корпус.
//
// В `typikon` лежит то, что делаем МЫ: тексты, дни, святцы, храмы. Эта база
// целиком пересобирается у нас и целиком уезжает на сервер (`release-db.sh`,
// `mongorestore --drop`) — накатывается поверх, а не сливается.
//
// Посты же заводятся НА ПРОДЕ: их готовит крон по проложным чтениям дня, там же
// их правят и подтверждают к отправке. Локально их нет и быть не должно. Пока
// они лежали в `typikon`, каждая выкладка корпуса везла на сервер здешнюю копию
// и `--drop` стирал подготовленные черновики — дожить до своего часа они просто
// не успевали.
//
// Оттого — в `typikon-users`, рядом с пользователями, их заметками и приходским,
// по той же причине и тем же путём (см. src/lib/parish/db.ts): выкладка корпуса
// туда не заглядывает вовсе, и стирать оттуда нечем.
//
// Переезд с прежнего места: `npm run channel-posts:move`.
export const channelPostsDb = async () => (await clientPromise).db("typikon-users");


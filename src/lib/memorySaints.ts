/**
 * Звания по основе, а не списком форм: книга пишет их в любом падеже и изредка
 * с опечаткой («Священномученника»), и ни одна такая форма не должна стать
 * именем.
 */
const TITLE_STEM = /^(?:свят|преподобн|священномуч|новосвященномуч|новомуч|мучени|великомуч|первомуч|блаж|праведн|равноап|исповедн|священноисп|страстот|апостол|пророк|праотц|благоверн|чудотвор|богоносн|юродив|бессребр|безмездн|иже|отц|отец|матер|епископ|архиеп|митропол|патриарх|игумен|архимандр|пресвитер|иерея|иерею|диакон|архидиак|инок|схимона|монах|старц|царевич|царев|цар|княз|княгин)/;

const isTitle = (w: string) => STOP.has(bare(w)) || TITLE_STEM.test(bare(w));

/** Слова, говорящие о женском лице: звания и чины в родительном женского рода. */
const FEMININE = /(?:^|\s)(?:святыя|преподобныя|блаженныя|праведныя|благоверныя|мученицы|великомученицы|преподобномученицы|первомученицы|равноапостольныя|княгини|царицы|матере|девы|вдовицы)(?:\s|$)|zhena|muchenitsa|prepodobnaya|muchenitsy/;

/** Слово подписи начинается с прописной — у книги это имя или прозвание, а не звание. */
const isCapital = (w: string) => /^[А-ЯЁ]/.test(w);

/** Имена, чей родительный правилом не разворачивается. */
const NAME_EXCEPTIONS: Record<string, string> = {
    павла: "Па́вел", петра: "Пётр", льва: "Лев", марка: "Марк", луки: "Лука́", фомы: "Фома́",
    саввы: "Са́вва", никиты: "Ники́та", илии: "Илия́", иеремии: "Иереми́я", исаии: "Иса́ия", захарии: "Заха́рия",
    михаила: "Михаи́л", даниила: "Дании́л", гавриила: "Гаврии́л", самуила: "Самуи́л", иоиля: "Иои́ль",
    измаила: "Измаи́л", кузьмы: "Кузьма́", козмы: "Козма́", иакова: "Иа́ков", иосифа: "Ио́сиф",
};

/**
 * Имя в именительном падеже из родительного. Мужские: «-а» после согласной
 * отпадает (Алекса́ндра → Алекса́ндр), «-ия/-ея/-ая» дают «-ий/-ей/-ай»
 * (Се́ргия → Се́ргий, Андре́я → Андре́й, Никола́я → Никола́й), «-ы/-и» дают «-а»
 * (Ники́ты → Ники́та). Женские: «-ы» → «-а», «-ии» → «-ия», «-и» после г/к/х → «-а»,
 * иначе «-и» → «-я».
 */
export const nominativeName = (gen: string, feminine: boolean): string => {
    const key = bare(gen);
    if (NAME_EXCEPTIONS[key]) return NAME_EXCEPTIONS[key];
    // Дательный — так пишет подписи Минея дополнительная, по образцу тропаря:
    // «Платону», «Василию», «Николаю».
    if (!feminine && /у[\u0300\u0301\u0311]?$/.test(gen) && /[бвгджзклмнпрстфхцчшщ]у[\u0300\u0301\u0311]?$/.test(gen)) {
        return gen.normalize("NFC").replace(/у([\u0300\u0301\u0311]?)$/, "");
    }
    if (!feminine && /[иеа][\u0300\u0301\u0311]?ю$/.test(gen.normalize("NFC"))) return gen.normalize("NFC").replace(/ю$/, "й");
    // Дательный мужских на «-а»: «святителю Луке», «Никите». Родительный на «-е»
    // у мужского имени не кончается, так что правило ничего не задевает.
    if (!feminine && /[бвгджзклмнпрстфхцчшщ]е[\u0300\u0301\u0311]?$/.test(gen)) return gen.normalize("NFC").replace(/е([\u0300\u0301\u0311]?)$/, "а$1");
    const m = /^(.*?)([а-яё])([̀́̑]?)$/i.exec(gen.normalize("NFC"));
    if (!m) return gen;
    const [, stem, last, accent] = m;
    const prev = bare(stem).slice(-1);
    if (feminine) {
        if (last === "ы") return `${stem}а${accent}`;
        if (last === "и" && prev === "и") return `${stem}я${accent}`;
        if (last === "и" && /[гкх]/.test(prev)) return `${stem}а${accent}`;
        if (last === "и") return `${stem}я${accent}`;
        return gen;
    }
    if (last === "я" && /[иеа]/.test(prev)) return `${stem}й`;
    // Мягкая основа: «Ла́заря» → «Ла́зарь», «И́горя» → «И́горь».
    if (last === "я" && /[бвгджзклмнпрстфхцчшщ]/.test(prev)) return `${stem}ь`;
    if (last === "а" && !/[аеёиоуыэюя]/.test(prev)) return stem.replace(/[̀́̑]$/, "");
    if (last === "ы" || (last === "и" && /[гкх]/.test(prev))) return `${stem}а${accent}`;
    return gen;
};

/**
 * Прозвание-прилагательное в именительном: «Не́вскаго» → «Не́вский»,
 * «Вели́каго» → «Вели́кий», «Пра́веднаго» → «Пра́ведный»; женское «Ки́евския» →
 * «Ки́евская», «-ыя» → «-ая».
 */
export const nominativeAdjective = (gen: string, feminine: boolean): string => {
    const s = gen.normalize("NFC");
    // Ударное окончание пишется с ударением внутри («Тверска́го»), и сличаем мы
    // его без знака; ударным оно даёт «-о́й»: Тверско́й, а не «Тверский».
    const stressed = /[аяо]\u0301(?:го|му)$|ы\u0301я$/.test(s);
    const plainEnd = s.replace(/([аяоы])\u0301(го|му|я)$/, "$1$2");
    if (feminine) {
        if (/ыя$/.test(plainEnd)) return plainEnd.replace(/ыя$/, stressed ? "а́я" : "ая");
        if (/([гкх])ия$/.test(plainEnd)) return plainEnd.replace(/ия$/, "ая");
        if (/ия$/.test(plainEnd)) return plainEnd.replace(/ия$/, "яя");
        // Русский родительный женского рода: «Се́рбской» → «Се́рбская».
        if (/[скц]кой$/.test(plainEnd)) return plainEnd.replace(/ой$/, "ая");
        return s;
    }
    if (stressed && /(?:аго|ому)$/.test(plainEnd)) return plainEnd.replace(/(?:аго|ому)$/, "о́й");
    if (/([гкхжшчщ][\u0300\u0301\u0311]?)аго$/.test(plainEnd)) return plainEnd.replace(/аго$/, "ий");
    if (/аго$/.test(plainEnd)) return plainEnd.replace(/аго$/, "ый");
    if (/яго$/.test(plainEnd)) return plainEnd.replace(/яго$/, "ий");
    // Дательный Минеи дополнительной: «Ревельскому» → «Ревельский».
    if (/([гкхжшчщ][\u0300\u0301\u0311]?)ому$/.test(plainEnd)) return plainEnd.replace(/ому$/, "ий");
    if (/ому$/.test(plainEnd)) return plainEnd.replace(/ому$/, "ый");
    if (/ему$/.test(plainEnd)) return plainEnd.replace(/ему$/, "ий");
    return s;
};

/** Прилагательное родительного падежа — кандидат в прозвание. */
const isAdjective = (w: string, feminine: boolean) =>
    feminine ? /(?:ския|цкия|ыя|ия|ской|цкой)$/.test(bare(w)) : /(?:аго|яго|ому|ему)$/.test(bare(w));

export interface MemoryPerson {
    /** «Алекса́ндр Не́вский» — имя и прозвание, с ударениями книги. */
    name: string;
    /** Имя без прозвания: «Алекса́ндр». */
    given: string;
    epithet: string | null;
    feminine: boolean;
    /** В подписи больше одного лица («Митрофа́на и Ти́хона»): такое решает человек. */
    several: boolean;
    /** Ключ сведения памятей одного лица: имя и прозвание без ударений. */
    key: string;
}

/**
 * Лицо из подписи памяти. null — имени не нашлось (праздник, собор, икона,
 * «Ина служба»). Прозвание — первое прилагательное с прописной после имени,
 * в том числе в оборотах «пе́рваго епи́скопа Воро́нежскаго».
 */
export const personOf = (label: string, chin: string | null = null): MemoryPerson | null => {
    // Подпись заглавными («СВЯТА́ГО СВЯЩЕННОМУ́ЧЕНИКА ГРИГО́РИЯ…») приводим к
    // словам с прописной: звания всё равно отсекаются по основе, а имя
    // получает обычный вид.
    const letters = label.replace(/[^А-Яа-яЁё]/g, "");
    const shouting = letters.length > 0 && letters.replace(/[^А-ЯЁ]/g, "").length / letters.length > 0.6;
    const text = shouting
        ? label.toLowerCase().replace(/(^|[\s,(«"-])([а-яё])/g, (_, a, b) => a + b.toUpperCase())
        : label;
    // Праздник иконы или образа — не память лица, даже если святой в подписи
    // назван: «Пра́зднование… ра́ди чудотво́рнаго его́ о́браза „Зара́йскаго“».
    if (/(?:^|[\s,(«"])(?:образ[а-я]*|икон(?:а|ы|е|у|ой)?|нерукотвор[а-я]*)(?:[\s,)»".]|$)/.test(bare(text))) return null;
    const clean = text.normalize("NFC").replace(/\([^()]*\)/g, " ").replace(/[«»"]/g, "");
    const tokens = clean.split(/[\s,:;.]+/).filter(Boolean);
    const feminine = FEMININE.test(bare(clean)) || FEMININE.test(chin ?? "");
    const at = tokens.findIndex((w) => bare(w).length > 1 && isCapital(w) && !isTitle(w) && !isAdjective(w, feminine));
    if (at < 0) return null;
    // Составное имя приводится по частям: «Иоа́нна-Влади́мира» → «Иоа́нн-Влади́мир».
    const given = tokens[at].split("-").map((part) => nominativeName(part, feminine)).join("-");
    // Прозвание ищем только до слова, за которым начинается другой человек:
    // «Фео́дора Яросла́вича, бра́та… Алекса́ндра Не́вскаго» — «Не́вский» не его.
    const after = tokens.slice(at + 1);
    const stopAt = after.findIndex((w) => /^(брата|сына|дщери|отца|матере|ученика|сродника|внука|супруга|супруги)$/.test(bare(w)));
    const rest = stopAt < 0 ? after : after.slice(0, stopAt);
    const adj = rest.find((w) => isCapital(w) && isAdjective(w, feminine) && !isTitle(w));
    const epithet = adj ? nominativeAdjective(adj, feminine) : null;
    // Второе имя, связанное с первым союзом: «Митрофа́на и Ти́хона», «Бори́са и Гле́ба».
    const several = /(?:^|\s)и\s+[А-ЯЁ]/.test(clean.slice(clean.indexOf(tokens[at]) + tokens[at].length))
        && rest.some((w, i) => i > 0 && rest[i - 1] === "и" && isCapital(w) && !isAdjective(w, feminine) && !isTitle(w));
    const name = epithet ? `${given} ${epithet}` : given;
    return { name, given, epithet, feminine, several, key: bare(name) };
};


// имя выводится здесь — окончаниями, с короткими исключениями.
//
// СУБЪЕКТ АДРЕСА ДЛЯ СВЕДЕНИЯ НЕ ГОДИТСЯ. У 23 ноября он вышел
// «alexander-the-great-vladimir»: «вели́каго кня́зя» прочтено прозвищем, а
// «Влади́мирскаго» — местом. Сводим памяти одного лица по выведенному имени с
// прозванием, а адрес берём только как ответ «это память лица».
//
// УДАРЕНИЯ СОХРАНЯЮТСЯ: имя каталога пишется с ними («Серги́й Ра́донежский»), и
// отрезается только окончание — ударение в основе остаётся где стояло.

const ACUTE = /[̀́̑]/g;

/** Без ударений, строчными, «ё» как «е»: для сличения. */

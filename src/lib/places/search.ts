// ПОИСК МЕСТА ПО ИМЕНИ.
//
// Правило приведения живёт здесь одно на всех, а не в странице указателя, где
// было прежде: тем же поиском теперь ищет приложение через `/api/v2/places`, и
// две копии правила разошлись бы молча — на сайте «Вифлеем» находился бы по
// «вифлеем», а в приложении нет.
//
// Приводим к нижнему регистру, сводим «ё» к «е» и выбрасываем пробелы с
// дефисами: в корпусе одно и то же место записано и «Беф-Ель», и «Бефель», и
// «Беф Ель», а читатель наберёт как придётся.
//
// Индекса в Mongo под это нет и не нужно: мест открытых чуть больше тысячи, а
// `$text` не умеет ни «ё», ни склейку дефисов — то есть искал бы не то, что
// ищет сайт.

/** Как сравниваем имена мест: и запрос, и само имя проходят через это. */
export const normalize = (s: string): string =>
    s.toLowerCase().replace(/ё/g, "е").replace(/[\s-]+/g, "");

/** Что за именами места стоит искать, кроме основного названия. */
export interface Searchable {
    name?: string | null;
    names?: { name?: string | null; transliteration?: string | null }[] | null;
    synonyms?: (string | null)[] | null;
}

/**
 * Стог, по которому ищем: основное имя, имена по эпохам с их латинской записью и
 * прежние синонимы — приведённые и сшитые через `|`.
 *
 * Разделитель обязателен и обязан переживать приведение: сшив имена пробелом,
 * мы получили бы «римафины» и находили бы место по обрывку, перескакивающему
 * границу имён.
 *
 * Имена по эпохам ищутся наравне с основным нарочно: «Царьград» должен находить
 * Константинополь, а «Эль-Кудс» — Иерусалим. В этом и смысл указателя.
 */
export const haystackOf = (row: Searchable): string => {
    const parts: string[] = [];
    if (row.name) parts.push(row.name);
    for (const n of row.names ?? []) {
        if (n?.name) parts.push(n.name);
        if (n?.transliteration) parts.push(n.transliteration);
    }
    for (const s of row.synonyms ?? []) if (s) parts.push(s);

    return parts.map(normalize).join("|");
};

/** Подходит ли место под набранное. Пустой запрос подходит всему. */
export const matches = (haystack: string, query: string): boolean => {
    const needle = normalize(query.trim());
    return needle ? haystack.includes(needle) : true;
};

// ПРАВА НА ТЕКСТЫ МОЛИТВОСЛОВА И СЛУЖЕБНИКА — что API вправе отдать наружу.
//
// Источник истины — rules/rights.yaml соседнего проекта typikon-rules: там
// решение владельца (may_redistribute) по каждому изданию. typikon-web читает
// артефакт сборки (rulesDb), в котором этой карты нет — editions несёт лишь
// лицензию и заметку, — поэтому вывод rights.yaml по нужным здесь изданиям
// продублирован константой ниже. Правило в typikon-rules изменится — менять
// и её: молча разойтись с владельцем здесь нечем, таблица маленькая.
//
// Доктрина корпуса (typikon-web/LICENSE-CORPUS.md): «верная передача текста,
// свободного от притязаний, своего права не порождает» — оцифровки старинных
// книг с azbyka.ru, условий на которые никто не заявил, раздаются дальше.
// Покрывает слои «Молитвослов» (гражданским и уставным шрифтом) и «Служебник».
//
// НЕ ПОКРЫВАЕТ английский слой Молитвослова: чей перевод, в корпусе не
// записано (editions.rights_note у molitvoslov-azbyka-en: «пока переводчик
// и права не выяснены, в выгрузку не идёт»). Поэтому en здесь не отдаётся
// вовсе — ни в поимённых молитвах, ни в последованиях, какой бы язык ни
// попросили.

/** Издания (source_book в fixed_texts), чьи тексты API отдавать вправе. */
const REDISTRIBUTABLE_BOOKS = new Set(["molitvoslov", "sluzhebnik", "chasoslov", "rules"]);

/**
 * Можно ли отдать текст этого издания наружу. Язык проверяется отдельно:
 * право держит ИЗДАНИЕ, а у молитвослова английский слой — издание иное
 * (molitvoslov-azbyka-en), даже если в базе он числится тем же source_book.
 */
export const canRedistribute = (sourceBook: string | null, language: string | null): boolean => {
    if (!sourceBook || !REDISTRIBUTABLE_BOOKS.has(sourceBook)) return false;
    // Английский слой молитвослова — издание иное, и оно в выгрузку не шло.
    // Язык, которого мы не знаем, — тоже отказ: «неизвестно» в правах читается
    // как «нет» (так же поступает rules/rights.yaml с may_redistribute).
    if (sourceBook === "molitvoslov") return language === "cu_gr" || language === "cu";
    return true;
};

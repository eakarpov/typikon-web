import { test } from "node:test";
import assert from "node:assert/strict";
import { joinNames, NAME_PLACEHOLDERS, renderNamedPrayer } from "@/lib/molitvoslov/named";

// Подстановка имён в книжный шаблон. Формы пустого места у изданий разные,
// подмена одна, и разбираться с ней должен именно этот слой — ручке о ней
// знать незачем.

test("таблица замен покрывает все известные книжные формы", () => {
    const keys = NAME_PLACEHOLDERS.map(p => p.key);
    for (const expected of ["name-gr", "imyarek", "imyarek-cs", "parents-gr", "parents-cs"]) {
        assert.ok(keys.includes(expected), expected);
    }
});

test("гражданская форма: (имя) подменяется родительным падежом", () => {
    const text = renderNamedPrayer(
        "Спаси́, Го́споди, и поми́луй роди́телей мои́х (имя), сро́дников (имя).",
        [{ name: "їѡа́нна" }],
        "m",
    );
    assert.equal(text, "Спаси́, Го́споди, и поми́луй роди́телей мои́х Їѡа́нна, сро́дников Їѡа́нна.");
});

test("несколько имён — через запятую, с прописной", () => {
    assert.equal(
        renderNamedPrayer("Помяни́, Го́споди, имярек.", [{ name: "никола́ѧ" }, { name: "марі́и" }], "m"),
        "Помяни́, Го́споди, Никола́ѧ, Марі́и.",
    );
});

test("опечатка издания «имярек]» — место то же", () => {
    const text = renderNamedPrayer(
        "упоко́й ду́ши усо́пших рабо́в Твои́х имярек], Христе́ Бо́же наш.",
        [{ name: "їѡа́нна" }],
        "m",
    );
    assert.ok(text.includes("рабо́в Твои́х Їѡа́нна, Христе́ Бо́же наш."));
});

test("уставная форма: [и҆́мⷬ҇къ] подменяется, скобки не едут", () => {
    const text = renderNamedPrayer(
        "Сп҃сѝ, гдⷭ҇и, ѻ҆тца̀ моего̀ дꙋхо́внаго [и҆́мⷬ҇къ].",
        [{ name: "нікола́ѧ" }],
        "m",
    );
    assert.equal(text, "Сп҃сѝ, гдⷭ҇и, ѻ҆тца̀ моего̀ дꙋхо́внаго Нікола́ѧ.");
});

test("категория без имени читается поимённо: [роди́телей мои́хъ] + имена", () => {
    const withNames = renderNamedPrayer(
        "ѹ҆со́пшихъ ра̑бъ твои́хъ: [роди́телей мои́хъ], сро́дникѡвъ [и҆́мⷬ҇къ].",
        [{ name: "їѡа́нна" }],
        "m",
    );
    assert.equal(
        withNames,
        "ѹ҆со́пшихъ ра̑бъ твои́хъ: роди́телей мои́хъ Їѡа́нна, сро́дникѡвъ Їѡа́нна.",
    );
});

test("без имён — общая формула, без пустых мест и сдвоенных пробелов", () => {
    const text = renderNamedPrayer(
        "Спаси́, Го́споди, и поми́луй отца́ моего́ духо́внаго (имя), роди́телей мои́х (имя), сро́дников (имя), и вся ближния рода моего.",
        [],
        "m",
    );
    assert.equal(
        text,
        "Спаси́, Го́споди, и поми́луй отца́ моего́ духо́внаго, роди́телей мои́х, сро́дников, и вся ближния рода моего.",
    );
});

test("без имён уставная категория остаётся без скобок", () => {
    const text = renderNamedPrayer(
        "ѹ҆со́пшихъ ра̑бъ твои́хъ: [роди́телей мои́хъ], сро́дникѡвъ [и҆́мⷬ҇къ].",
        [],
        "m",
    );
    assert.equal(text, "ѹ҆со́пшихъ ра̑бъ твои́хъ: роди́телей мои́хъ, сро́дникѡвъ.");
});

test("чин идёт перед именем в родительном падеже", () => {
    const text = renderNamedPrayer(
        "Помяни́, Го́споди, ду́ши усо́пших рабо́в Твои́х имярек.",
        [{ name: "никола́ѧ", rank: "ierey" }],
        "m",
    );
    assert.ok(text.includes("рабо́в Твои́х і҆ере́ѧ Никола́ѧ."));
});

test("женская форма чина — по полу лица, а не молящегося", () => {
    const text = renderNamedPrayer(
        "Помяни́, Го́споди, имярек.",
        [{ name: "марі́и", rank: "igumen", sex: "f" }],
        "m",
    );
    assert.ok(text.includes("и҆гꙋ́менїи Марі́и."));
});

test("пол лица неизвестен — чин по полу молящегося", () => {
    const male = renderNamedPrayer("имярек.", [{ name: "никола́ѧ", rank: "igumen" }], "m");
    const female = renderNamedPrayer("имярек.", [{ name: "никола́ѧ", rank: "igumen" }], "f");
    assert.ok(male.startsWith("и҆гꙋ́мена"));
    assert.ok(female.startsWith("и҆гꙋ́менїи"));
});

test("шаблон без места под имена возвращается как есть", () => {
    const intact = "Помяни́, Го́споди, благотворя́щия нам, ми́лующия и пита́ющия нас.";
    assert.equal(renderNamedPrayer(intact, [{ name: "їѡа́нна" }], "m"), intact);
});

test("неизвестная форма пустого места не подменяется молча", () => {
    // Формы вне таблицы (опечатка разбора, другое издание) должны быть видны,
    // а не уехать читателю как подменённый текст.
    const text = renderNamedPrayer("Помяни́, Го́споди, раба Твоего́ (и́мярекъ).", [{ name: "їѡа́нна" }], "m");
    assert.ok(text.includes("(и́мярекъ)"));
});

test("joinNames: пустой список — пустая строка", () => {
    assert.equal(joinNames([], "m"), "");
    assert.equal(joinNames([{ name: "  " }], "m"), "");
});

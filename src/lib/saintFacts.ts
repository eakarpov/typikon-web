/**
 * `baseYear` — НЕ год кончины, хотя чаще всего совпадает с ним. У святцев это
 * год того события, по которому память поставлена в ряд: преставление,
 * перенесение мощей, написание образа, явление (dneslov, Memory#set_base_year).
 * Поэтому подпись — «опорный год», а не крестик: крестик утверждал бы то,
 * чего в поле не сказано.
 *
 * Числа около -9999 у них означают не год, а «прежде времени»: -9999 у Троицы,
 * -9998 у Христа, -9996 у Духа, -9995 у Креста. 0 — «не выяснено». Ни то, ни
 * другое не год, и показывать их нечем; а вот -5500 у «Мира» — их настоящий
 * счёт от сотворения, и он остаётся.
 */
const BEFORE_TIME = -9000;

export const baseYearLabel = (year: number | null | undefined): string | null => {
    if (!year || year <= BEFORE_TIME) return null;
    return year < 0 ? `${-year} до Р. Х.` : String(year);
};

// ── Дни памяти ───────────────────────────────────────────────────────────────
//
// Формат `year_date` святцев задан их же проверкой (dneslov, Memo:725):
//
//     (ДД.ММ([%<>~][0-6])?) | ([+-]\d{1,3})
//
//   ДД.ММ    — постоянная дата ЮЛИАНСКОГО счёта (то, что в месяцеслове);
//   [+-]N    — переходящая: столько дней от Пасхи (+0 — сама Пасха);
//   [%<>~]N  — привязка к дню недели, N считается от воскресенья
//              (Memo::DAYS = нд пн вт ср чт пт сб).
//
// Из привязок считаем только `%` — «первый такой день недели, начиная с
// этого числа» (Memo::CONDITIONALS: 0..6 вперёд). Три остальных в каталоге не
// встречаются ни разу, и правило их знаков мы не проверяли; для них показываем
// само число и помету словами, а гражданский день не называем. Посчитать
// непроверенное — тот же обман, что и показать догадку сопоставителя за
// сведение.

/** Дни недели святцев: их счёт идёт от воскресенья, наш (ch.WEEKDAYS) — от понедельника. */
const DNESLOV_WEEKDAYS = ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"];

/** «первое воскресенье», но «первая суббота»: род у дней недели разный, и слух это ловит. */
const FIRST_WEEKDAY = [
    "первое воскресенье", "первый понедельник", "первый вторник", "первая среда",
    "первый четверг", "первая пятница", "первая суббота",
];

const FIXED = /^(\d{2})\.(\d{2})(?:([%<>~])([0-6]))?$/;
const MOVABLE = /^([+-])(\d{1,3})$/;

export interface MemoryDay {
    /** Как записано у святцев: «16.12», «+49», «12.07%0». */
    raw: string;
    /** Постоянное число юлианского счёта — «16 декабря». У переходящих пусто. */
    julian: string | null;
    /** Гражданский день ближайшего наступления — «29 декабря 2026». */
    civil: string | null;
    /** Тот же день адресом для /calculator/{iso}. */
    iso: string | null;
    /** Чем дата держится, словами. У обычного числа пусто — там и так всё видно. */
    note: string | null;
}

const isoOf = (jdn: number): string => {
    const { year, month, day } = ch.jdnToGregorian(jdn);
    return `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
};

/** Первый такой день недели, начиная с самого дня (привязка `%`). */
const forwardTo = (jdn: number, dneslovWeekday: number): number => {
    const target = DNESLOV_WEEKDAYS[dneslovWeekday];
    for (let shift = 0; shift < 7; shift += 1) {
        if (ch.weekdayOf(jdn + shift) === target) return jdn + shift;
    }
    return jdn;
};

/**
 * Один день памяти на ближайшее его наступление от `today`.
 *
 * Год берём тот, в котором день ещё не прошёл: карточку читают, чтобы узнать,
 * КОГДА, а прошедшее число этого не отвечает. Смена стиля тут не наша выдумка
 * и не «плюс тринадцать»: юлианское число переводится в гражданское через
 * юлианский день, и разница выходит сама — она разная в разные века.
 */
export const memoryDayOf = (raw: string, today: Date): MemoryDay | null => {
    const value = (raw ?? "").trim();
    if (!value) return null;

    const civilYear = today.getUTCFullYear();
    const todayJdn = ch.gregorianToJdn({
        year: civilYear, month: today.getUTCMonth() + 1, day: today.getUTCDate(),
    });

    const movable = MOVABLE.exec(value);
    if (movable) {
        const offset = (movable[1] === "-" ? -1 : 1) * Number(movable[2]);
        const at = (year: number) => ch.paschaJdn(year) + offset;
        const jdn = at(civilYear) < todayJdn ? at(civilYear + 1) : at(civilYear);
        return {
            raw: value,
            julian: null,
            civil: showYmd(ch.jdnToGregorian(jdn)),
            iso: isoOf(jdn),
            // Теми же словами, какими адресует память реестр (addressOf в
            // @/lib/memories): «49-й день по Пасхе» на одной странице и «+49» на
            // другой читались бы как два разных сведения.
            note: offset === 0 ? "сама Пасха"
                : offset > 0 ? `${offset}-й день по Пасхе`
                : `за ${-offset} дней до Пасхи`,
        };
    }

    const fixed = FIXED.exec(value);
    if (!fixed) return null;

    const day = Number(fixed[1]);
    const month = Number(fixed[2]);
    if (month < 1 || month > 12 || day < 1 || day > 31) return null;

    const [, , , sign, weekday] = fixed;
    const julian = showYmd({ year: civilYear, month, day }, false);

    // Привязка, которой мы не считаем: число называем, гражданский день — нет.
    if (sign && sign !== "%") {
        return {
            raw: value, julian, civil: null, iso: null,
            note: `привязана к дню недели (${DNESLOV_WEEKDAYS[Number(weekday)]}) от этого числа`,
        };
    }

    const at = (year: number) => {
        const base = ch.julianToJdn({ year, month, day });
        return sign === "%" ? forwardTo(base, Number(weekday)) : base;
    };
    const jdn = at(civilYear) < todayJdn ? at(civilYear + 1) : at(civilYear);

    return {
        raw: value,
        julian,
        civil: showYmd(ch.jdnToGregorian(jdn)),
        iso: isoOf(jdn),
        note: sign === "%" ? `${FIRST_WEEKDAY[Number(weekday)]} с этого числа` : null,
    };
};

/** Дни памяти записи, по порядку ближайшего наступления. Неразобранное отбрасываем молча. */
export const memoryDaysOf = (dates: string[] | null | undefined, today: Date): MemoryDay[] => {
    const days = (dates ?? [])
        .map((date) => memoryDayOf(date, today))
        .filter((day): day is MemoryDay => Boolean(day));
    return days.sort((a, b) => (a.iso ?? "9999").localeCompare(b.iso ?? "9999"));
};

// Источник скана: рукопись или старопечатная книга на lib-fond.ru.
//
// Ссылки на сканы стоят у текстов давно (`texts.link`), но ведут они в
// «Изображения» конкретного листа — «откуда это взято» из такого адреса не
// прочитать. Название несёт сама страница описи: «Ф.7 №13. Паренесис Ефрема
// Сирина. [Другое заглавие:] Заголовок рукописи: "Книги святаго и праведнаго
// отца нашего Ефрема Сурианина…"». Его и забираем — раз, скриптом, — а
// показываем под текстом.
//
// Хранится это в коллекции `sources`, отдельно от текстов, и намеренно: одна
// рукопись стоит источником у десятков текстов (у Ф.299 №582 их 36), и
// класть её название в каждый значило бы держать три десятка копий, которые
// разойдутся при первой же правке описи.

/** Адрес описи без якоря: `#image-21` указывает лист, а опись одна на рукопись. */
export const libFondUrl = (link: string | null | undefined): string | null => {
    if (!link || !link.includes("lib-fond.ru")) return null;
    const base = link.split("#")[0].split("?")[0];
    return base.endsWith("/") ? base : `${base}/`;
};

// Шифр в адресе: `f-228-52` — Ф.228 №52, `f-173i-51` — Ф.173.I №51.
// Римская часть номера фонда пишется в адресе слитной латинской «i».
const CIPHER_RE = /\/(?:f-)(\d+)(i*)-(\d+)\/?$/;

/**
 * Короткий шифр из самого адреса: «Ф.228 №52».
 *
 * Нужен как запасной вариант — на случай, когда полного названия у нас нет
 * (опись не забрана, сайт не ответил, адрес новый). Пустая строка вместо
 * источника читалась бы как «источник неизвестен», тогда как шифр известен
 * всегда: он записан в самой ссылке.
 *
 * У старопечатных книг (`/mk-rgb/<слаг>/`) шифра нет вовсе — там опись
 * названа словами, и без забранного названия сказать нечего.
 */
export const libFondCipher = (link: string | null | undefined): string | null => {
    const url = libFondUrl(link);
    if (!url) return null;
    const m = url.match(CIPHER_RE);
    if (!m) return null;
    // Сама опись пишет римскую часть через косую: «Ф.173/I №51», «Ф.304/I №103».
    // Запасной шифр должен читаться так же, как настоящий, иначе одна и та же
    // рукопись под текстом и в описи выглядит по-разному.
    const roman = m[2] ? `/${"I".repeat(m[2].length)}` : "";
    return `Ф.${m[1]}${roman} №${m[3]}`;
};

export interface LibFondSource {
    url: string;
    /** Название описи целиком, как его печатает lib-fond. */
    title: string | null;
    cipher: string | null;
}

/** Что показать под текстом: название, если оно забрано, иначе хотя бы шифр. */
export const sourceLabel = (source: LibFondSource | null | undefined): string | null => {
    if (!source) return null;
    return source.title || source.cipher || null;
};

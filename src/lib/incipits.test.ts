import { test } from "node:test";
import assert from "node:assert/strict";
import { normalizeIncipitQuery, INCIPIT_WORDS } from "@/lib/incipits";

// Все ожидания ниже сверены с самой таблицей text_incipits, а не выведены из
// чтения кода сборки: под каждым лежит запрос к корпусу, показавший именно эту
// строку. Иначе тест закрепил бы нашу догадку о ключе, а не ключ.

test("ударения и надстрочные снимаются", () => {
    // «Свете Тихий» лежит в корпусе как «свете тихии»: 3 вхождения.
    assert.equal(normalizeIncipitQuery("Све́те Ти́хий"), "свете тихии");
});

test("«й» сводится к «и» — в отличие от поиска по песнопениям", () => {
    // Это самое опасное место раздела. В @/lib/chants «й» СОХРАНЯЕТСЯ, потому
    // что токенизатор FTS5 его не разбирает. Здесь наоборот: ключ строится
    // через NFD, «й» распадается на «и» + краткое, краткое снимается вместе с
    // ударениями. Зачинов с «й» в таблице ровно ноль.
    assert.equal(normalizeIncipitQuery("Ра́дуйся"), "радуися");
    assert.equal(normalizeIncipitQuery("Радуйся Благодатная"), "радуися благодатная");
    assert.doesNotMatch(normalizeIncipitQuery("Радуйся"), /й/);
});

test("«ё» сводится к «е»", () => {
    assert.equal(normalizeIncipitQuery("Её"), "ее");
});

test("кириллица переживает чистку пунктуации", () => {
    // Ловушка перевода с Python: там `[^\w\s]` оставляет кириллицу, потому что
    // `\w` юникодный. В JavaScript `\w` — только ASCII, и та же регулярка
    // выкосила бы славянский текст до пустой строки.
    const out = normalizeIncipitQuery("Господи, воззвах к Тебе!");
    assert.equal(out, "господи воззвах к тебе");
    assert.notEqual(out, "");
});

test("греческий: тонос и придыхания снимаются, буквы остаются", () => {
    // В корпусе: «η γεννησις σου χριστε ο θεος» — тропарь Рождества.
    assert.equal(
        normalizeIncipitQuery("Ἡ Γέννησίς σου Χριστὲ ὁ Θεὸς"),
        "η γεννησις σου χριστε ο θεος",
    );
});

test("пунктуация становится границей слов, а не склейкой", () => {
    // «Спаси, Господи» без замены на пробел дало бы «спасигосподи».
    assert.equal(normalizeIncipitQuery("Спаси, Господи"), "спаси господи");
    assert.equal(normalizeIncipitQuery("Сла́ва, и ны́не:"), "слава и ныне");
});

test("запрос обрезается по числу слов зачина", () => {
    // Ключ длиннее шести слов не бывает: седьмое слово не сузило бы выдачу,
    // а обнулило — под такой префикс не подошёл бы ни один зачин.
    const long = "воду прошед яко сушу и египетскаго зла избежав";
    assert.equal(normalizeIncipitQuery(long).split(" ").length, INCIPIT_WORDS);
    assert.equal(normalizeIncipitQuery(long), "воду прошед яко сушу и египетскаго");
});

test("лишние пробелы схлопываются", () => {
    assert.equal(normalizeIncipitQuery("  воду   прошед \n яко "), "воду прошед яко");
});

test("строка из одних знаков препинания даёт пустой запрос", () => {
    // Пустой префикс — это «весь указатель», и страница обязана отличать его от
    // осмысленного запроса, а не искать по нему.
    for (const raw of ["", "  ", "!!!", "«»:—", "%\\"]) {
        assert.equal(normalizeIncipitQuery(raw), "");
    }
});

test("подстановочные знаки не имеют силы: поиск идёт диапазоном, не LIKE", () => {
    // В LIKE «%» и «_» были бы операторами. Здесь они просто выкидываются как
    // не-буквы, и экранировать нечего — в этом и смысл выбора диапазона.
    assert.equal(normalizeIncipitQuery("воду%"), "воду");
    // А вот подчёркивание переживает чистку — и намеренно: в Python `\w`
    // включает `_`, и сборка ключа его сохраняет. Мы обязаны совпадать со
    // сборкой буква в букву, иначе набранное не сойдётся с записанным. В
    // богослужебном тексте подчёркивания не бывает, так что цена нулевая.
    assert.equal(normalizeIncipitQuery("во_у"), "во_у");
});

test("цифры сохраняются: они есть и в самих зачинах", () => {
    // В таблице 2 087 зачинов с цифрами — следы разбора вроде «1 ангелов царице».
    // Сводить их к пустоте нельзя: тогда такой зачин стал бы недостижим.
    assert.equal(normalizeIncipitQuery("1 Ангелов Царице"), "1 ангелов царице");
});

// Отбор святых по набранному в поиске. Вынесено из страницы отдельно ради тестов:
// вся соль тут в нормализации, а её ошибка не падает, а тихо не находит.
//
// ПОЧЕМУ ОТБОР В ПАМЯТИ, А НЕ ЗАПРОСОМ В БАЗУ. Указатель и так строится целиком:
// он считает тексты по всему собранию и держит результат в кэше (см. saints/api.ts).
// Восемь сотен строк уже в руках, и городить ради них второй путь — текстовый индекс
// Mongo с нормализованными копиями имён — значит завести ещё одно место, где имя
// может разойтись с каталогом. Когда памятей станут десятки тысяч, это перестанет
// быть верным; пока — нет.
//
// ИЩЕМ И ПО АЛЬТЕРНАТИВНЫМ ИМЕНАМ. Ровно ради этого они и собраны: «Дева Мария»
// должна находить Богородицу, а мирское «Алекса» — Варлаама Хутынского.
import { normalizeChurchSlavonic } from "@/utils/churchSlavonic";

export interface SearchableSaint {
    name: string | null;
    altNames?: string[];
}

/**
 * Приведение к сравнимому виду: снимаются ударения и церковнославянские надстрочные,
 * ѣ и прочие буквы кладутся на современные. Без этого «Феофано» не находит
 * «Феофа́но» — комбинирующее ударение стоит внутри слова отдельным символом.
 *
 * Побочно «й» становится «и», а «ё» — «е»: краткая и умляут для NFD такие же
 * надстрочные знаки, как ударение. Для поиска это к лучшему — запрос проходит ту же
 * нормализацию, значит «византийская» и «византиискаѧ» встречаются, — но знать об
 * этом надо: сравнивать этой функцией ИМЕНА на равенство нельзя, она для отбора.
 */
export const normalizeForSearch = (value: string): string =>
    normalizeChurchSlavonic(value).replace(/\s+/g, " ").trim();

/** Слова запроса. Пустой запрос — пустой список, и тогда отбор не применяется вовсе. */
export const searchTerms = (query: string): string[] =>
    normalizeForSearch(query || "").split(" ").filter(Boolean);

/**
 * Совпадение по И, а не по ИЛИ: «иоанн злат» должно находить Златоуста, а не всех
 * Иоаннов разом. Слова могут стоять в разных именах одного святого — ищем по всей
 * его горсти имён сразу, а не по каждому отдельно.
 */
export const saintMatches = (saint: SearchableSaint, terms: string[]): boolean => {
    if (!terms.length) return true;
    const haystack = normalizeForSearch([saint.name ?? "", ...(saint.altNames ?? [])].join(" "));
    return terms.every((term) => haystack.includes(term));
};

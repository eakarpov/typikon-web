// Церковнославянская орфография для ПОРОЖДЁННЫХ форм.
//
// Словарь-источник (script-data/data.csv, он же typikon-csl.lexems) набран не всей
// ЦС-графикой: в 148 216 формах нет ни одного ѧ, ꙗ, ꙋ — вместо них всюду я и у
// (я ×44 083, ѧ ×0). Прочие буквы он держит: і ×27 814, ѣ ×27 398, ѡ ×19 768, а
// также є, ѿ, ѻ, ѳ, ѵ, ѕ, ѯ, ѱ. Таблицы парадигм записаны в той же графике, что и
// словарь, — чтобы их можно было сверять со словарём буква в букву.
//
// Наружу так отдавать нельзя: «я» в церковнославянском наборе не бывает вовсе.
// Выбор между ꙗ и ѧ позиционный, и здесь он и делается — одним проходом по готовой
// форме, а не в каждой таблице по отдельности.

/** Йотированный аз: начало слова. */
const IOTATED_A = "ꙗ"; // ꙗ
/** Юс малый: середина и конец. */
const SMALL_YUS = "ѧ"; // ѧ

/** Ук-диграф: начало слова. */
const UK_DIGRAPH = "ᲂу"; // ᲂу
/** Ук-лигатура: середина и конец. */
const UK = "ꙋ"; // ꙋ

/** Камора: облечённое ударение. */
export const KAMORA = "̑";

const VOWELS = "аеёиоуыэюяєѣіїѵѡѻꙋѹѧѫꙗѩᲂ";

/**
 * Ставит камору на последнюю гласную ФОРМЫ (основа с окончанием).
 *
 * Камора в церковнославянском наборе — не просто ударение, а знак, снимающий
 * грамматическую омонимию: раба̑ (дв. им.) против раба̀ (ед. род.), ра̑бъ (мн. род.)
 * против ра́бъ (ед. им.). В таблицах Полякова она помечена крышкой, и без неё
 * порождённая форма совпала бы с чужой.
 *
 * Считаем от конца: в «раба̑» (дв. им.) знак падает на окончание, а в «ра̑бъ» (мн. род.
 * с нулевым окончанием) — на гласную основы, и последняя гласная формы в обоих случаях
 * та самая. У многосложной основы с нулевым окончанием это уже догадка: камора стоит
 * там, где было бы ударение, а ударения таблицы не знают. Форма без гласных возвращается
 * как есть.
 */
export const withKamora = (form: string): string => {
    const chars = [...form];
    for (let i = chars.length - 1; i >= 0; i--) {
        if (!VOWELS.includes(chars[i])) continue;
        chars.splice(i + 1, 0, KAMORA);
        return chars.join("");
    }
    return form;
};

/**
 * Приводит порождённую форму к церковнославянской графике.
 *
 * Правило позиционное: в начале слова — ꙗ и ᲂу, в середине и конце — ѧ и ꙋ.
 * Заглавная Я остаётся Ꙗ в любом положении: с заглавной слово и начинается.
 */
export const toChurchSlavonic = (word: string) =>
    [...word]
        .map((ch, index) => {
            if (ch === "я") return index === 0 ? IOTATED_A : SMALL_YUS;
            if (ch === "Я") return "Ꙗ"; // Ꙗ
            if (ch === "у") return index === 0 ? UK_DIGRAPH : UK;
            if (ch === "У") return "У";
            return ch;
        })
        .join("");

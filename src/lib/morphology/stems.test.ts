import { test } from "node:test";
import assert from "node:assert/strict";
import { cut, cutSuffix, splitClitic } from "@/lib/morphology/stems";

// Основа слова: что от леммы отрезается и что к ней прирастает.

test("отрезаемое считается буквами, а не знаками", () => {
    // В «лице́» последний символ — ударение, а не «е»: простой replace(/е$/) тут
    // не срабатывает вовсе, и порождение выдавало «лице́е» вместо «лица́».
    assert.equal(cut("лице́", "е"), "лиц");
    assert.equal(cutSuffix("глаго́лати", "ти"), "глаго́ла");
});

test("несовпадение возвращает лемму целиком — и это надо помнить", () => {
    // Молчаливый откат: основой становится всё слово, и дальше к нему клеится
    // окончание. Ради этого и заведено отделение частицы ниже.
    assert.equal(cut("сло́во", "а"), "сло́во");
    assert.equal(cutSuffix("сло́во", "ти"), "сло́во");
});


// Приставшая частица. Плюс в словаре — граница морфем, а не знак слова: не
// отделив его, порождение приписывало окончание к целому инфинитиву.
test("частица отделяется от слова, а плюс не остаётся в ней", () => {
    assert.deepEqual(splitClitic("ви́дѣти+же"), { head: "ви́дѣти", clitic: "же" });
    assert.deepEqual(splitClitic("боя́тися+бо"), { head: "боя́тися", clitic: "бо" });

    // Выписанные в словаре формы пишутся слитно («бла́гоже»), и порождённые
    // должны выглядеть так же — плюс в них не переезжает.
    assert.equal(splitClitic("бла́го+же").clitic.includes("+"), false);
});

test("двух частиц подряд хватает тоже", () => {
    assert.deepEqual(splitClitic("моли́тися+бы+бо"), { head: "моли́тися", clitic: "быбо" });
    assert.deepEqual(splitClitic("диви́тися+ли+ти"), { head: "диви́тися", clitic: "лити" });
});

test("слово без частицы остаётся собой", () => {
    assert.deepEqual(splitClitic("глаго́лати"), { head: "глаго́лати", clitic: "" });
    assert.deepEqual(splitClitic(""), { head: "", clitic: "" });
});

// Типы чувашской азбуки. Движок (engine.js) выгружается из проекта azbuki
// дословно, поэтому описание его поверхности живёт здесь, а не в нём.

/** Словники: всё, что нельзя вывести правилом. */
export interface ChuvashData {
    /** Поимённые решения: Осия с точкой снизу, Эдем через корень. */
    spellings: Record<string, string>;
    /** Основы имён: по ним движок отличает имя от почтительной заглавной. */
    names: string[];
    /** Имена с греческими буквами: Матѳей, Виѳлеем, Коринѳ. */
    greek: Record<string, string>;
    /** Слова под титлом — закрытый перечень, как в славянской книге. */
    titla: Record<string, string>;
}

/** Переключатели того, что в азбуке ещё не закреплено. */
export interface Options {
    /** off — не оглушать, loans — только заимствования, all — и имена. */
    devoice: "off" | "loans" | "all";
    /** Чем держится конечная звонкая: паерок, ер буквой или ничем. */
    final: "paerok" | "jer" | "off";
    /** Ставить ли титла (и убирать ли заглавные внутри строки). */
    titla: boolean;
}

export interface Piece {
    text: string;
    src: string;
    /** Буквы, которых чувашский язык не требует: они остаются в именах. */
    foreign: string[];
    name: boolean;
    titlo?: boolean;
}

export interface Translit {
    translit(text: string): Piece[];
    word(src: string, sentenceStart?: boolean): Piece;
    opt: Options;
}


import { test } from "node:test";
import assert from "node:assert/strict";
import { locationOf, pageUrl, placeKindOf, relicsOf, shrinesSection, unwiki, whereStems } from "./azbyka";

const LAVRA = `{{Местоположение святыни|локация=56.310, 38.130|вид=Монастырь}}
'''Свято-Троицкая Сергиева лавра'''
== История ==
Мощи здесь упомянуты в истории, но не в разделе.
== Святыни ==
* Мощи прп. Сергия Радонежского (в Троицком соборе)
* Мо­щи прп. Ни­ко­на Радонежского (в Троицком соборе)
* Мощи свт. Исаи Ростовского (глава) (в Серапионовой палате)
* Частица мощей вмч. Меркурия (в Серапионовой палате)
* Икона Божией Матери «Тихвинская» (в Троицком соборе)
* До революции здесь хранились мощи [[Иов (Патриарх)|свт. Иова]]
Текст после списка.
== Престольные праздники ==
* Мощи из другого раздела не в счёт
`;

test("точка и вид из шаблона", () => {
    assert.deepEqual(locationOf(LAVRA), { lat: 56.31, lon: 38.13 });
    assert.equal(placeKindOf(LAVRA), "Монастырь");
    assert.equal(locationOf("без шаблона"), null);
    assert.equal(locationOf("{{Местоположение святыни|локация=0, 0}}"), null);
});

test("раздел — до следующего заголовка", () => {
    const s = shrinesSection(LAVRA)!;
    assert.ok(s.includes("Сергия"));
    assert.ok(!s.includes("другого раздела"));
    assert.equal(shrinesSection("== История ==\nнет"), null);
});

test("строки-мощи: святой, уточнение, вид; иконы не берутся", () => {
    const r = relicsOf(LAVRA);
    assert.equal(r.length, 5);
    assert.equal(r[0].saintGuess, "прп. Сергия Радонежского");
    assert.equal(r[0].where, "в Троицком соборе");
    assert.equal(r[0].kind, "moshchi");
    assert.equal(r[1].saintGuess, "прп. Никона Радонежского");
    assert.equal(r[3].kind, "chastitsa");
    assert.equal(r[3].saintGuess, "вмч. Меркурия");
    assert.equal(r[4].former, true);
    assert.equal(r[4].line, "До революции здесь хранились мощи свт. Иова");
});

test("разметка вики снимается", () => {
    assert.equal(unwiki("'''Мощи''' [[Сергий Радонежский|прп. Сергия]] <ref>x</ref> [https://a.ru сайт]"), "Мощи прп. Сергия сайт");
});

test("основы храма из уточнения", () => {
    assert.deepEqual(whereStems("в Троицком соборе"), ["троицк"]);
    assert.deepEqual(whereStems("в Серапионовой палате"), ["серапионов"]);
    assert.deepEqual(whereStems(null), []);
});

test("адрес страницы", () => {
    assert.equal(pageUrl("Свято-Троицкая Сергиева лавра"),
        "https://azbyka.ru/palomnik/%D0%A1%D0%B2%D1%8F%D1%82%D0%BE-%D0%A2%D1%80%D0%BE%D0%B8%D1%86%D0%BA%D0%B0%D1%8F_%D0%A1%D0%B5%D1%80%D0%B3%D0%B8%D0%B5%D0%B2%D0%B0_%D0%BB%D0%B0%D0%B2%D1%80%D0%B0");
});

const MULTI = `== Святыни ==
* Ковчежец с частицами мощей святителей Воронежских Митрофана и Тихона и преподобных Кирилла и Марии Радонежских
* Икона с частицами мощей Святых благоверных князя Петра и княгини Февронии, Муромских.
* Иконы с частицами мощей: святой мученицы Татианы (подарена братией Псково-Печерского монастыря), святого преподобного Серафима Саровского
* Миро с мощей великомученика Димитрия Солунского
* Часть мира от мощей святителя Николая
* Масло от мощей св. Спиридона
`;

test("строка с несколькими святыми делится на находки, прозвания — подсказкой", () => {
    const r = relicsOf(MULTI);
    assert.deepEqual(r.map((x) => x.saintGuess), [
        "святителей Митрофана", "святителей Тихона", "преподобных Кирилла", "преподобных Марии",
        "Святых благоверных князя Петра", "княгини Февронии",
        "святой мученицы Татианы", "святого преподобного Серафима Саровского",
    ]);
    assert.equal(r[0].context, "Воронежских");
    assert.equal(r[2].context, "Радонежских");
    assert.equal(r[5].context, "Муромских");
});

test("миро, масло и «часть мира» не мощи", () => {
    assert.ok(!relicsOf(MULTI).some((x) => /Димитрия|Николая|Спиридона/.test(x.saintGuess ?? "")));
});

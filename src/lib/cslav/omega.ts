// Положение омеги: чем решается спор «о» против «ѡ».
//
// ЗАЧЕМ. Обратная проверка по Минее показала, что омега — самый крупный блок
// расхождений: 1 036 из 1 903, больше половины. Идёт он в обе стороны почти
// поровну, значит это не одно недостающее правило, а положение омеги как
// таковое: родительное окончание «-агѡ» против винительного «-аго», дательное
// множественное «-ѡмъ» против творительного единственного «-омъ», наречие
// против краткого прилагательного, приставки, начало слова.
//
// ЧЕМ РЕШАЕТСЯ. Не грамматикой — её пришлось бы выводить из разбора
// предложения, которого у слоя нет, — а ПОЛОЖЕНИЕМ в слове: две буквы слева от
// спорной гласной и хвост слова справа.
//
// Замер на отложенных днях Минеи (63 686 мест с о/ѡ, из них омега в 16,9%):
// таблица ставит омегу 5 900 раз и верна в 98,9% из них; мест угадано верно
// 92,2% против 83,1% у безусловного «всегда о».
//
// ЧЕГО ОНО НЕ ДЕЛАЕТ. Оно не спорит с книгой: где написание засвидетельствовано,
// берётся книга. Правило работает там, где книги молчат или расходятся, — то
// есть решает спор, а не подменяет свидетельство.

/** Контекст → что в нём стоит: «о» или «ѡ». */
export type OmegaTable = Record<string, "о" | "ѡ">;

/**
 * Ключи контекста от частного к общему.
 *
 * Порядок существен: сперва спрашивается самый узкий контекст (две буквы слева
 * и весь хвост справа), и только если о нём таблица молчит — более общий.
 * Так редкое слово получает ответ по своему окончанию, а частое — по себе.
 */
export const omegaKeys = (word: string, at: number): string[] => {
    const left = (n: number) => word.slice(Math.max(0, at - n), at);
    const tail = word.slice(at + 1);
    return [
        `2|∞|${left(2)}●${tail}`,
        `1|∞|${left(1)}●${tail}`,
        `0|∞|●${tail}`,
        `2|2|${left(2)}●${tail.slice(0, 2)}`,
        `1|1|${left(1)}●${tail.slice(0, 1)}`,
        `0|1|●${tail.slice(0, 1)}`,
        `1|0|${left(1)}●`,
    ];
};

/** Что таблица говорит об этом месте; null — молчит. */
export const omegaAt = (table: OmegaTable, word: string, at: number): "о" | "ѡ" | null => {
    for (const key of omegaKeys(word, at)) {
        const found = table[key];
        if (found) return found;
    }
    return null;
};

const DISPUTED = /[оѡ]/;

/**
 * Согласуется ли написание с положением омеги.
 *
 * Считает места, где таблица говорит своё, и возвращает долю согласия. Слово
 * без спорных гласных или вовсе не узнанное таблицей даёт null: сказать о нём
 * нечего, и молчание честнее нуля.
 */
export const omegaAgreement = (table: OmegaTable, word: string): number | null => {
    let asked = 0;
    let agreed = 0;
    for (let at = 0; at < word.length; at++) {
        if (!DISPUTED.test(word[at])) continue;
        const says = omegaAt(table, word, at);
        if (!says) continue;
        asked++;
        if (says === word[at]) agreed++;
    }
    return asked ? agreed / asked : null;
};

/**
 * Различаются ли два написания ТОЛЬКО буквами о и ѡ.
 *
 * Правило прикладывается лишь к такому спору: если написания разнятся ещё
 * чем-то, положение омеги о них не судит.
 */
export const onlyOmegaApart = (a: string, b: string): boolean => {
    if (a.length !== b.length || a === b) return false;
    let differs = 0;
    for (let at = 0; at < a.length; at++) {
        if (a[at] === b[at]) continue;
        if (!DISPUTED.test(a[at]) || !DISPUTED.test(b[at])) return false;
        differs++;
    }
    return differs > 0;
};

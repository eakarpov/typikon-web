import { normalizeChurchSlavonic } from "@/utils/churchSlavonic";
import { toChurchSlavonic } from "@/lib/morphology/orthography";

// Гражданка → церковнославянская графика: общее ядро.
//
// ЗАДАЧА НЕ ЯЗЫКОВАЯ, А ГРАФИЧЕСКАЯ. Требуется не перевод, а восстановление
// написания: «тебе» → «тебѣ̀» или «тебѐ». Правилом это не делается, потому что
// свёртка @/utils/churchSlavonic необратима по построению — е получается из
// {е, ѣ, є}, о из {о, ѡ, ѻ}, у из {у, ꙋ, ѹ, ᲂу}, я из {я, ѧ, ꙗ}. Значит нужен
// словарь; где словарь молчит — грамматика; где молчит и она — пометка вместо
// догадки.
//
// ЧТО ЗДЕСЬ ЛЕЖИТ. Ключ, которым сходятся обе стороны; приведение написания к
// единой графике (без него один и тот же облик считается за два разных); и
// позиционные правила, которых в словаре нет по построению.

/**
 * Гражданский ключ: то, чем сходятся гражданское написание и церковнославянское.
 *
 * Свёртка плюс снятие конечного ера — тем же приёмом, что `searchKey` в
 * словаре: иначе «воззвах», набранное человеком, не найдёт «воззва́хъ».
 */
export const civilKey = (word: string): string =>
    normalizeChurchSlavonic(word).trim().replace(/ъ$/, "");

// Уставные начертания (кириллица расширенная C) — те же буквы, нарисованные
// по-уставному. В указателе они обязаны сойтись с обычными, иначе «пасᲅырь» и
// «пастырь» встанут двумя разными написаниями одного слова.
const USTAV: Record<string, string> = {
    "ᲀ": "в", "ᲁ": "д", "ᲂ": "о", "ᲃ": "с", "ᲄ": "т",
    "ᲅ": "т", "ᲆ": "ъ", "ᲇ": "ѣ", "ᲈ": "ꙋ",
};

// Ук: диграф ᲂу, слитный ѹ, монограф ꙋ и просто «оу» двумя обычными буквами —
// одна буква, записанная четырьмя способами. Юс: я, ꙗ и ѧ — одна буква,
// различающаяся положением. Приводим и то и другое к положению: в начале слова
// диграф ука и ꙗ, внутри — монограф и ѧ. Так набрано собрание и так же делает
// toChurchSlavonic при порождении форм; без этого «мѧ̀» и «мя̀», «оу҆́бѡ» и
// «ᲂу҆́бѡ» встают спорной парой, хотя буква в них одна.
const UK_ANY = /^оу|ᲂу|ѹ|ꙋ|у/g;
const YUS_ANY = /я|ꙗ|ѧ/g;

/**
 * Единая церковнославянская графика.
 *
 * Сводит уставные начертания и позиционные варианты ука; ѣ/е, ѡ/о и і/и НЕ
 * трогает — это выбор написания, а не начертание, и стирать его нельзя.
 *
 * Нужна при сборке указателя: без неё «ꙗ҆́кѡ», «ꙗ҆́кѡ» уставным т и «ѩ҆́кѡ»
 * считаются тремя написаниями, и спор возникает там, где его нет.
 */
export const csCanonical = (word: string): string => {
    const ustav = [...word].map((ch) => USTAV[ch] ?? ch).join("");
    const uk = ustav.replace(UK_ANY, (_m, offset: number) => (offset === 0 ? "ᲂу" : "ꙋ"));
    const yus = uk.replace(YUS_ANY, (_m, offset: number) => (offset === 0 ? "ꙗ" : "ѧ"));
    return yus.normalize("NFC");
};

/** Какие правила приложены к слову, когда словарь промолчал. */
export type RuleName = "юс" | "ук" | "ер" | "звательце" | "от" | "ударение" | "титло";

// Приставка «от» пишется лигатурой ѿ, а корневое «от» — обычными буквами:
// «ѿи҆дѐ», но «ѻ҆те́цъ». Замерено по собранию: через ѿ — 12 700
// словоупотреблений, иначе — 850, и эти 850 сплошь корневые. Корни выписаны
// отсюда же, а не из головы: 156 ключей сводятся к десятку основ.
const OT_ROOTS = [
    "ец", "ц", "ч", "рок", "роч", "роц", "рав", "яг", "ай", "ец",
];

export interface RuleResult {
    form: string;
    applied: RuleName[];
}

// Узкое о (U+1C82) — первая буква диграфа ука, и без него звательце не встало
// бы над «ᲂу҆слы́ши»: к этому месту toChurchSlavonic уже превратил «у» в диграф.
const VOWELS = "аеиоуыэюяєѣіѵꙋѡѧꙗᲂ";
const PSILI = "҆";

/**
 * Позиционные правила — то, чего в словаре нет по построению.
 *
 * ЗВАТЕЛЬЦЕ И ЕР — по замеру, а не по учебнику: в собрании звательце стоит у
 * 142 877 слов с начальной гласной из 150 543 (94,9%), а конечный ер — у
 * 103 902 слов против 7 373 без него.
 *
 * ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ: не восстанавливает ѣ, ѡ, ѻ, і, ї, є, ѕ, ѳ, ѵ. Эти
 * буквы стоят не по положению, а по слову и по форме, и угадать их нельзя —
 * «воззва́хъ» правило даст, а «тебѣ̀» не даст никогда.
 */
export const byRule = (word: string): RuleResult => {
    const applied: RuleName[] = [];

    // Приставка «от» — лигатурой; корень — нет.
    let source = word;
    let prefix = "";
    const low = word.toLocaleLowerCase("ru");
    // Предлог «от» сам по себе — тоже приставка: в собрании он 7 725 раз пишется ѿ.
    if (low.startsWith("от") && !OT_ROOTS.some((root) => low.slice(2).startsWith(root))) {
        prefix = "ѿ";
        source = word.slice(2);
        applied.push("от");
    }

    // Юс и ук ставит toChurchSlavonic — единственный в проекте код в эту
    // сторону, выверенный порождением парадигм. Второе его написание здесь
    // немедленно разошлось бы с первым.
    let form = toChurchSlavonic(source);
    if (/[ѧꙗ]/.test(form) && !/[ѧꙗ]/.test(source)) applied.push("юс");
    if (/[ᲂуꙋ]/.test(form) && !/[ᲂꙋ]/.test(source)) applied.push("ук");

    // Конечный ер после согласной.
    if (/[бвгджзклмнпрстфхцчшщ]$/i.test(form)) {
        form += "ъ";
        applied.push("ер");
    }

    if (prefix) return { form: prefix + form, applied };

    // Звательце над начальной гласной. Ставится после буквы: это надстрочный
    // знак, а не буква.
    const first = [...form][0] ?? "";
    if (VOWELS.includes(first.toLowerCase()) && !form.includes(PSILI)) {
        const rest = form.slice(first.length);
        // У диграфа ука звательце стоит над второй буквой: «ᲂу҆слы́ши».
        form = first === "ᲂ" && rest.startsWith("у")
            ? `${first}у${PSILI}${rest.slice(1)}`
            : `${first}${PSILI}${rest}`;
        applied.push("звательце");
    }

    return { form, applied };
};

/**
 * Вернуть регистр исходного слова переведённому.
 *
 * Не тождество: «У» переходит в диграф «Оу҆» — один гражданский знак против
 * двух церковнославянских, — и наивное посимвольное приведение здесь врёт.
 */
export const matchCase = (source: string, target: string): string => {
    const head = [...source][0] ?? "";
    if (!head || head.toLocaleLowerCase("ru") === head) return target;

    const chars = [...target];
    if (chars[0] === "ᲂ" && chars[1] === "у") {
        // Прописной диграф пишется обычными О и у.
        return `О${chars.slice(1).join("")}`;
    }
    chars[0] = chars[0].toLocaleUpperCase("ru");
    // Слово целиком прописными — так набраны заголовки книг.
    const rest = [...source].slice(1).join("");
    if (rest && rest === rest.toLocaleUpperCase("ru")) return chars.join("").toLocaleUpperCase("ru");
    return chars.join("");
};

/** Уже церковнославянское написание: такое слово не трогаем вовсе. */
export const hasChurchSlavonicGraphics = (word: string): boolean =>
    /[ѣѧꙗѡѻѹꙋѕѯѱѳѵіїєѫᲀ-ᲈ҃-҉ⷠ-ⷿ]/.test(word);


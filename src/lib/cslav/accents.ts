import { placeAccent, type AccentAnswer } from "@/lib/accents/core";

// Ударение для слова, пришедшего правилом.
//
// Правило даёт буквы, но не знает, на какой слог падает голос: это не
// позиционный вопрос, а словарный. Зато на него отвечает словарь ударений,
// на котором стоит раздел «Ударения», — 293 891 запись по книгам собрания,
// песнопениям и церковнославянскому словарю.
//
// СТАВИМ ТОЛЬКО НЕСПОРНОЕ. У раздела «Ударения» спорные места показываются
// человеку списком; здесь показывать их негде — слово и так помечено как
// пришедшее правилом, и добавлять к одной неуверенности вторую значило бы
// выдать догадку за ответ. Поэтому: либо источник единодушен, либо слово
// остаётся без ударения.

/** Во сколько раз ведущее ударение должно обходить соперника. */
export const DOMINANCE_FOR_ACCENTS = 10;

/**
 * Гражданское слово с ударением по словарю; null — словарь молчит или спорит.
 *
 * Ударение ставится на ГРАЖДАНСКОЕ написание, а не на церковнославянское, и
 * это существенно: в церковнославянском диграф ука записан двумя знаками
 * («ᲂу»), счёт гласных разошёлся бы с гражданским, и знак встал бы не туда.
 */
export const accentedByDictionary = (word: string, answer: AccentAnswer): string | null => {
    if (!answer.known) return null;

    // Порядок источников тот же, что у чтений в разделе «Ударения»: книги
    // собрания, потом песнопения, потом словарь.
    for (const source of [answer.corpus, answer.chants]) {
        if (!source.length) continue;
        const [best, rival] = source;
        if (rival && best.count < DOMINANCE_FOR_ACCENTS * rival.count) return null;
        return placeAccent(word, best.vowel, best.mark);
    }

    // У словаря частот нет: принимаем его ответ, только если он один.
    if (answer.lexicon.length === 1) {
        const only = answer.lexicon[0];
        return placeAccent(word, only.vowel, only.mark);
    }
    return null;
};

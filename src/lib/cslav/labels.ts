// Подписи грамматических помет — по-русски и для читателя.
//
// Чистый словарь: сюда не ходит ничто, кроме данных, и оттого он безопасен для
// браузера — то же правило, что у @/lib/razbor/labels.
//
// Пометы словаря записаны сокращениями латиницей («dat/loc», «brev,sg,m,gen»),
// и в таком виде они читателю ничего не говорят. А сказать надо: спор между
// «тебѣ̀» и «тебѐ» — это спор о падеже, и ответ на него даёт помета, а не
// частота.

const TAGS: Record<string, string> = {
    nom: "именительный",
    gen: "родительный",
    dat: "дательный",
    acc: "винительный",
    ins: "творительный",
    loc: "местный",
    voc: "звательный",
    sg: "единственное",
    du: "двойственное",
    pl: "множественное",
    m: "мужской",
    f: "женский",
    n: "средний",
    brev: "краткая форма",
    plen: "полная форма",
    clit: "энклитика",
    anim: "одушевлённое",
    imper: "повелительное",
    indic: "изъявительное",
    aor: "аорист",
    imperf: "имперфект",
    praes: "настоящее",
    perf: "перфект",
    "1p": "1-е лицо",
    "2p": "2-е лицо",
    "3p": "3-е лицо",
};

/**
 * Помета словаря по-русски: «dat/loc» → «дательный или местный».
 *
 * Косая черта у словаря значит «и то и другое», запятая — перечисление,
 * вертикальная — разные разборы одной формы. Незнакомую помету оставляем как
 * есть: выдумывать ей русское имя хуже, чем показать исходную.
 */
export const CASE_LABELS = (properties: string): string =>
    properties
        .split("|")
        .map((reading) => reading
            .split(",")
            .map((group) => group
                .split("/")
                .map((tag) => TAGS[tag.trim()] ?? tag.trim())
                .join(" или "))
            .filter(Boolean)
            .join(", "))
        .join(" · ");

// Часть речи ЛЕКСЕМЫ — отдельно от помет формы, и в одном случае она решает
// написание. Наречие на -о пишется омегой («вѣ́рнѡ», «досто́йнѡ», «свѣ́тлѡ»),
// краткое прилагательное среднего рода — обычным о («вѣ́рно», «свѣ́тло»). В
// гражданке это омонимы, и различает их только часть речи. У формы наречия
// грамматических помет нет вовсе, и без этой подписи спор выходил безымянным:
// читатель видел два написания и ни слова о том, чем они разнятся.
const SPEECH: Record<string, string> = {
    ADV: "наречие",
    A: "прилагательное",
    S: "существительное",
    V: "глагол",
    PRO: "местоимение",
    SPRO: "местоимение-существительное",
    APRO: "местоимение-прилагательное",
    NUM: "числительное",
    PR: "предлог",
    CONJ: "союз",
    PART: "частица",
    INTJ: "междометие",
};

/** Часть речи по-русски: «ADV» → «наречие», «S,n,inan» → «существительное». */
export const SPEECH_LABEL = (properties?: string): string => {
    if (!properties) return "";
    const head = properties.split(",")[0].trim();
    return SPEECH[head] ?? "";
};

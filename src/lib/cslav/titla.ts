const bagOf = (word: string) => [...word].sort().join("");

const isSubsequence = (part: string, whole: string): boolean => {
    let at = 0;
    for (const ch of whole) if (ch === part[at]) at++;
    return at === part.length;
};

/**
 * Может ли полное слово стоять за этим сокращением.
 *
 * Три условия разом, и каждое отсекает свой род ошибок:
 *   — набор букв тот же: сокращение букв не добавляет и не теряет, коль скоро
 *     выносная опущена в строку;
 *   — первая буква сохранена: без этого «єⷭ҇» связывается с «се» вместо «есть»,
 *     а «реⷱ҇» — с «чре» вместо «рече» (558 и 372 ложные связки при замере);
 *   — строчные буквы идут в том же порядке: не на месте только выносная, и
 *     ровно её перестановку правило и допускает («тⷯѣ» → «тѣхъ»).
 *
 * @param lowered костяк с опущенной выносной, без конечного ера
 * @param base    он же без выносных вовсе — то, что стояло в строке
 */
export const fitsSkeleton = (lowered: string, base: string, candidate: string): boolean =>
    candidate.length > 0
    && candidate[0] === base[0]
    && bagOf(candidate) === bagOf(lowered)
    && isSubsequence(base, candidate);

// --- Извод сокращения: синодальный или дониконовский ----------------------
//
// ЗАЧЕМ РАЗЛИЧАТЬ. Перевод идёт в синодальное написание, а собрание держит и
// старопечатные книги («Маргарит» — 5 638 сокращений обычных слов из 6 442 по
// всему собранию). В синодальной печати под титло уходит закрытый круг слов —
// священные имена и их производные; всё прочее пишется полностью. Дониконовский
// же набор сокращал ради места что угодно: «ᲂу҆́мѡⷨ» — это «ᲂу҆́момъ» с поднятой
// над строкой м, и предлагать такое как норму нельзя.
//
// ЧЕМ ПРОВЕРЕНО. Елизаветинская Библия — печать синодальной эпохи — даёт 13 542
// слова под титлом, 474 вида, и все до одного суть сокращения священных слов:
// гдⷭ҇ь, хрⷭ҇та̀, і҆ерⷭ҇ли́мъ, млⷭ҇ть, блгⷣть, спⷭ҇нїе, прⷪ҇ро́къ, црⷭ҇тво, прⷭ҇нѡ. Ни
// одного сокращения обычного слова там нет.
//
// ПРИЗНАК. Два условия разом:
//   — под титлом ОПУЩЕНЫ буквы, а не просто поднята одна над строкой: если
//     выносную опустить в строку и выйдет то же слово целиком, это экономия
//     места, а не сокращение («ѡⷮ» → «от», «наⷭ҇» → «насъ», «ᲂу҆́мѡⷨ» → «ᲂу҆́момъ»);
//   — слово священное, то есть несёт одну из выверенных основ — где бы она в
//     слове ни стояла: «пребл҃же́нне» сокращается по «блж», хотя основа стоит
//     после приставки.

/** Сокращения синодальной печати, не выводимые из основ. */
const SYNODAL_WORDS = new Set([
    // «зач҃» — указание зачала в Евангелии и Апостоле, печатается киноварью.
    "зач", "зачало", "зачала",
    // Счёт времени в месяцеслове: «мцⷭ҇а», «лѣ́то».
    "месяца", "месяц",
]);

const STEMS_BY_LENGTH = Object.keys(TITLA_STEMS).sort((a, b) => b.length - a.length);

/** Несёт ли слово выверенную основу — где бы она ни стояла. */
export const hasSacredStem = (skeleton: string): boolean =>
    STEMS_BY_LENGTH.some((stem) => skeleton.includes(stem));

export type TitloEra = "synodal" | "old";

/**
 * Какого извода это сокращение.
 *
 * @param spelling сокращение как оно напечатано
 * @param word     полное слово, к которому оно привязано (гражданский ключ)
 */
export const titloEra = (spelling: string, word: string): TitloEra => {
    // Выносную опустили — и вышло то же слово: букв не опущено, это экономия
    // места дониконовского набора, а не сокращение священного слова.
    const lowered = titloSkeleton(spelling).replace(/ъ$/, "");
    if (lowered === word) return "old";

    if (SYNODAL_WORDS.has(word)) return "synodal";
    return hasSacredStem(civilSkeleton(spelling)) ? "synodal" : "old";
};

/** Костяк без выносных вовсе — то, что осталось в строке. */
const civilSkeleton = (spelling: string): string =>
    spelling.normalize("NFD").replace(/[\u0300-\u036f\u0483-\u0489\u2de0-\u2dff\ua674-\ua679]/g, "")
        .normalize("NFC").toLowerCase();

/**
 * Может ли полное слово стоять за сокращением, где буквы ОПУЩЕНЫ.
 *
 * Иное дело, чем fitsSkeleton: там выносная переставлена, и набор букв сходится;
 * здесь букв в сокращении меньше, и сходиться должен порядок. Условия:
 * первая и последняя буквы сохранены (титло никогда не съедает края слова),
 * остальные идут подпоследовательностью, и опущено не больше половины слова —
 * иначе под «гди» подойдёт пол-словаря.
 */
export const fitsContraction = (skeleton: string, candidate: string): boolean => {
    if (candidate.length <= skeleton.length) return false;
    if (candidate.length > skeleton.length * 2) return false;
    if (candidate[0] !== skeleton[0]) return false;
    if (candidate[candidate.length - 1] !== skeleton[skeleton.length - 1]) return false;
    let at = 0;
    for (const ch of candidate) if (ch === skeleton[at]) at++;
    return at === skeleton.length;
};


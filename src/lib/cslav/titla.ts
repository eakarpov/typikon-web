const CONTRACTIONS_BY_LENGTH = Object.keys(TITLA_CONTRACTIONS).sort((a, b) => b.length - a.length);

const IS_MARK = /[\u0300-\u036f\u0483-\u0489\u2de0-\u2dff\ua674-\ua679]/;

/**
 * Сокращение слова по образцу основы; null — основы в слове нет.
 *
 * Слово приходит церковнославянским, с ударением и своей графикой, а основы в
 * таблице записаны гражданскими буквами. Поэтому слово сперва проецируется в
 * гражданку с сохранением соответствия знакомест, основа ищется в проекции, и
 * заменяется уже в исходном написании — вместе со стоящими на ней знаками.
 */
export const contractByStem = (form: string): { form: string; stem: string } | null => {
    const chars = [...form];
    const civil: string[] = [];
    const at: number[] = [];
    chars.forEach((ch, index) => {
        if (IS_MARK.test(ch)) return;
        const plain = normalizeChurchSlavonic(ch);
        if (!plain) return;
        // «ѿ» разворачивается в две буквы: соответствие знакомест сбилось бы.
        if (plain.length !== 1) return;
        civil.push(plain);
        at.push(index);
    });
    const line = civil.join("");

    for (const stem of CONTRACTIONS_BY_LENGTH) {
        const found = line.indexOf(stem);
        if (found < 0) continue;
        const from = at[found];
        // Конец основы — вместе со знаками, стоящими над её последней буквой.
        let to = at[found + stem.length - 1] + 1;
        while (to < chars.length && IS_MARK.test(chars[to])) to++;
        return {
            form: chars.slice(0, from).join("") + TITLA_CONTRACTIONS[stem] + chars.slice(to).join(""),
            stem,
        };
    }
    return null;
};

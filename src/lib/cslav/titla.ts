/**
 * Раскрытие костяка сокращения: «гди» → «господи», «бгу» → «богу».
 *
 * Костяк — это слово со снятыми надстрочными знаками и выносными буквами.
 * Целые слова проверяются раньше основ; основа ищется с начала, самая длинная
 * из подходящих. Не узнали — возвращаем null: соврать раскрытием хуже, чем не
 * связать сокращение с его словом.
 */
export const expandTitlo = (skeleton: string): string | null => {
    const whole = TITLA_WORDS[skeleton];
    if (whole) return whole;

    const stems = Object.keys(TITLA_STEMS).sort((a, b) => b.length - a.length);
    for (const stem of stems) {
        if (!skeleton.startsWith(stem)) continue;
        return TITLA_STEMS[stem] + skeleton.slice(stem.length);
    }
    return null;
};

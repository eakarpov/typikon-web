/**
 * Раскрытие костяка сокращения: «гди» → «господи», «бгу» → «богу».
 *
 * Костяк — это слово со снятыми надстрочными знаками и выносными буквами.
 * Целые слова проверяются раньше основ; основа ищется с начала, самая длинная
 * из подходящих. Не узнали — возвращаем null: соврать раскрытием хуже, чем не
 * связать сокращение с его словом.
 */
export const expandTitlo = (skeleton: string): string | null => {
    const whole = TITLA_WORDS[skeleton];
    if (whole) return whole;

    const stems = Object.keys(TITLA_STEMS).sort((a, b) => b.length - a.length);
    for (const stem of stems) {
        if (!skeleton.startsWith(stem)) continue;
        return TITLA_STEMS[stem] + skeleton.slice(stem.length);
    }
    return null;
};

// --- Костяк с опущенной выносной ------------------------------------------
//
// ЗАЧЕМ ВТОРОЙ КОСТЯК. Общая свёртка (@/utils/churchSlavonic) выносную букву
// ОТБРАСЫВАЕТ, и для поиска это верно: она написана над строкой и в линейный
// порядок не встаёт («гдⷭ҇ь» с опущенной выносной дало бы «гдсь», тогда как в
// «господь» с стоит перед д). Но для связывания сокращения с полным словом
// отброшенная буква — потеря свидетельства: «нашиⷯ» сводится к «наши», а не к
// «нашихъ», и слово теряется. Поэтому здесь выносная опускается в строку, а
// порядок букв правится не позицией, а сверкой наборов (см. fitsSkeleton).
//
// КОНЕЧНЫЙ ЕР СОХРАНЯЕТСЯ, в отличие от civilKey. Он и отличает сокращение от
// числа: «б҇ъ» — это Бог, а «б҃» — двойка, и по свёрнутому ключу «б» они
// неразличимы.

/** Выносная буква → она же в строке. */
const LOWERED: Record<string, string> = {
    "ⷠ": "б", "ⷡ": "в", "ⷢ": "г", "ⷣ": "д", "ⷤ": "ж", "ⷥ": "з", "ⷦ": "к", "ⷧ": "л",
    "ⷨ": "м", "ⷩ": "н", "ⷪ": "о", "ⷫ": "п", "ⷬ": "р", "ⷭ": "с", "ⷮ": "т", "ⷯ": "х",
    "ⷰ": "ц", "ⷱ": "ч", "ⷲ": "ш", "ⷳ": "щ", "ⷴ": "ѳ", "ⷵ": "ст", "ⷶ": "а", "ⷷ": "е",
    "ⷸ": "ђ", "ⷹ": "ꙋ", "ⷺ": "ѣ", "ⷻ": "ю", "ⷼ": "ꙗ", "ⷽ": "ѧ", "ⷾ": "ѫ", "ⷿ": "ѭ",
    "ꙴ": "є", "ꙵ": "і", "ꙶ": "ї", "ꙷ": "у", "ꙸ": "ъ", "ꙹ": "ы",
};

const SUPERSCRIPT = /[\u2de0-\u2dff\ua674-\ua679]/g;

/** Есть ли в слове выносная буква. */
export const hasSuperscript = (word: string) => new RegExp(SUPERSCRIPT.source).test(word);

/** Костяк с опущенной в строку выносной; конечный ер сохраняется. */
export const titloSkeleton = (word: string): string =>
    normalizeChurchSlavonic(word.replace(SUPERSCRIPT, (ch) => LOWERED[ch] ?? ""));


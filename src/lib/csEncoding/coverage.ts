// Проверка того, какие церковнославянские знаки способен отобразить шрифт
// читателя. Здесь — только чистая часть: что считать доказательством и как
// понять, что измерение вообще состоялось.
//
// Измерения производит браузер (замер ширины и сравнение растров), и все они
// ошибаются известным образом: у шрифта может оказаться глиф ровно той ширины,
// что и .notdef; надстрочный знак имеет нулевую ширину и по ширине не
// проверяется вовсе; getImageData в защищённом режиме возвращает искажённые
// данные. Поэтому измерение всегда сопровождается контрольной парой, и при её
// провале выносится «проверить не удалось», а не «знака нет»: ложное
// утверждение об отсутствии знака хуже отсутствия проверки.

export type Verdict = "present" | "missing" | "unknown";

export const VERDICT_LABELS: Record<Verdict, string> = {
    present: "отображается",
    missing: "не отображается",
    unknown: "проверить не удалось",
};

export interface Measurement {
    /** Знак отличается по начертанию от заведомо отсутствующего. */
    differsFromNotdef: boolean;
    /** Контрольная пара: два заведомо различных знака дали различный результат. */
    controlPassed: boolean;
}

export const verdictOf = ({ differsFromNotdef, controlPassed }: Measurement): Verdict => {
    if (!controlPassed) return "unknown";
    return differsFromNotdef ? "present" : "missing";
};


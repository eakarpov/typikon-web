// UCS — не кодировка текста, а раскладка шрифта: байт означает не букву, а место
// в шрифте, и без этого шрифта текст читается мусором. Так набраны тысячи
// церковнославянских страниц, выложенных до юникода (irmologion.ru/ucsenc.html).
//
// ПОЧЕМУ БАЙТ, А НЕ ЗНАК. Ключ таблицы — значение байта, а не символ. Всякая
// таблица с ключами-знаками — это та же таблица, уже пропущенная через чью-то
// кодовую страницу, то есть производная, и производная с потерями: байт, которому
// в той странице не нашлось знака, из неё выпадает молча. Вставленный в окно текст
// возвращается к байтам обращением его декодера (./alphabets), а не второй
// таблицей: две таблицы одного и того же неминуемо разойдутся.
//
// ЗАПИСЬ ЭСКЕЙПАМИ. Половину этих знаков глазом не отличить друг от друга
// (ѡ от ѽ, і от и, ѻ от о), и опечатка в такой таблице ничем себя не выдаёт —
// в @/utils/churchSlavonic это уже случилось однажды. Правя строку, сверяйся
// с кодом, а не с начертанием.
//
// ОТКУДА ВЗЯТО И ЧЕМ ПРОВЕРЕНО. Источник — github.com/frogstail/ucs-decoder под
// CC0 (общественное достояние), 129 записей; остальные 127 байтов там не названы,
// и мы пропускаем их как в CP1251 — в этой части и стоит основа UCS. Сверено
// с независимым выводом той же раскладки: cslavonic (MIT, © 2016 Mike Kroutikov,
// транскрипция Perl-Lingua-CU А. Андреева), 256 записей. Из 129 общих байтов
// 121 совпали знак в знак, 1 — после NFC (0xB3 ї), расходятся 7 (см. UCS_DISPUTED),
// а на всех остальных байтах наш сквозной пропуск даёт то же, что и там.
//
// Третий независимый вывод этой раскладки существует (slavdict/hip2unicode), но
// у него нет лицензии вовсе, то есть все права сохранены, — и мы намеренно в него
// не смотрели.
//
// UCS — СЕМЕЙСТВО, А НЕ ОДНА КОДИРОВКА. Шрифты Hirmos, Irmologion, Triodion и
// прочие расходятся как раз в верхней половине; здесь разобран извод, описанный
// на irmologion.ru. Страница говорит об этом читателю прямо.


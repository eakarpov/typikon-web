// Церковнославянская транслитерация: буквы юникодом, надстрочные — латиницей.
//
// ЧТО ЭТО. Третья кодировка старых церковнославянских текстов после HIP и UCS,
// и устроена она иначе обеих. Буквы здесь настоящие кириллические, а всё, что
// стоит НАД строкой, записано латинскими буквами, цифрами и типографскими
// знаками, приставленными к своей букве справа: «є3ди1нъ» — это «є҆ди́нъ»,
// «сп7си2» — «сп҃сѝ», «прbр0къ» — «прⷪ҇ро́къ».
//
// ПОЧЕМУ ОТДЕЛЬНО ОТ HIP. У orthlib надстрочные тоже ASCII, но разметка другая
// («'» ударение, «=» звательце, «~» титло) и в текст вкраплены издательские
// пометы. Свести их в одну таблицу значило бы получить разбор, который на обоих
// работает наполовину.
//
// ОТКУДА ЗНАЧЕНИЯ. Выведены из самих текстов Октоиха по частым словам, где
// чтение однозначно («ћкw» — «ꙗ҆́кѡ», «гDи» — «гдⷭ҇и», «бцdа» — «бцⷣа»), и
// проверены сверкой с гражданским изданием того же Октоиха: свёрнутый в
// гражданку разбор обязан совпасть с ним, и каждая неверная строка таблицы
// немедленно видна расхождением.

const OXIA = "́";
const VARIA = "̀";
const KAMORA = "̑";
const PSILI = "҆";       // звательце
const TITLO = "҃";
const POKRYTIE = "҇";
const EROK = "̾";

/** Знак транслитерации → что он значит в юникоде. */
export const TRANSLIT: Record<string, string> = {
    // Надстрочные сами по себе.
    "1": OXIA,
    "2": VARIA,
    "3": PSILI,
    "4": PSILI + OXIA,
    "5": PSILI + VARIA,
    "7": TITLO,
    "8": EROK,
    "#": PSILI,

    // Буква вместе со своим знаком.
    "0": "о" + OXIA,
    "a": "а" + OXIA,
    "A": "а" + VARIA,
    "†": "а" + KAMORA,
    "e": "е" + OXIA,
    "E": "е" + VARIA,
    "B": "ѣ" + OXIA,
    "h": "ы" + OXIA,
    "6": "ы" + KAMORA,
    "H": "ѡ" + OXIA,
    "y": "ꙋ" + OXIA,
    "Y": "ꙋ" + VARIA,
    "j": "і" + OXIA,
    "s": "ѧ" + OXIA,
    "S": "ѧ" + VARIA,
    "‰": "ѧ" + KAMORA,

    // Буквы без знака.
    "z": "ѧ",
    "w": "ѡ",
    "t": "ѿ",
    "m": "ѷ",
    "k": "ꙗ" + PSILI,
    "n": "ѻ" + PSILI,

    // Сокращения: буква под титлом или выносная с покрытием.
    "9": "ж" + TITLO,
    "G": "г" + TITLO,
    "l": "л" + TITLO,
    "™": "т" + TITLO,
    "§": "ч" + TITLO,
    "}": "и" + TITLO,
    "b": "ⷪ" + POKRYTIE,          // выносная о
    "c": "ⷭ" + POKRYTIE,          // выносная с
    "d": "ⷣ",                     // выносная д
    "D": "дⷭ" + POKRYTIE,
    "L": "лⷣ",
    "R": "рⷭ" + POKRYTIE,
    "r": "рⷭ" + POKRYTIE,
    "C": "ⷭ" + POKRYTIE,          // прописной вариант «c»
    "¦": "х" + TITLO,
    "®": "рⷣ",
    "T": "Ѿ",
    "N": "Ѻ" + PSILI,
    "K": "Ꙗ" + PSILI,
    "Q": "Ѽ",
    "F": "Ѳ",

    // Буквы, которых нет в кириллической части раскладки.
    "o": "ѻ",
    "q": "ѽ",
    "u": "ᲂу",
    "v": "ѵ",
    "x": "ѯ",
    "p": "ѱ",
    "f": "ѳ",
    "i": "і",

    // Каморы и прочее над буквой.
    "{": "ꙋ" + KAMORA,
    "‡": "і" + KAMORA,
    "±": "ꙗ" + PSILI + VARIA,
    "%": PSILI + VARIA,           // прописной вариант «5»
    "№": "а" + TITLO,             // единица цифирью
};

/**
 * Кириллические буквы, которые в этой кодировке значат не себя.
 *
 * Их легко проглядеть: «э» здесь не «э», а ять, и глазом это не отличить от
 * гражданского текста. Отсюда и правило проекта — буквы кодами, а не
 * начертанием.
 */
export const TRANSLIT_LETTERS: Record<string, string> = {
    "э": "ѣ",                     // э
    "ё": "ѣ" + OXIA,              // ё
    "Ё": "ѣ" + VARIA,             // Ё
    "ў": "ᲂу" + PSILI,            // ў
    "ћ": "ꙗ" + PSILI + OXIA,      // ћ
    "џ": "ѻ" + PSILI + OXIA,      // џ
    "і": "і",                     // і остаётся собой
    "њ": "ѡ" + PSILI,             // њ
    "Њ": "Ѡ" + PSILI,             // Њ
    "Џ": "Ѻ" + PSILI + OXIA,      // Џ
    "Ў": "Оу" + PSILI,            // Ў
    "ќ": "ᲂу" + PSILI + OXIA,     // ќ
    "Ќ": "Оу" + PSILI + OXIA,     // Ќ
    "Ћ": "Ꙗ" + PSILI + OXIA,      // Ћ
};

const KEYS = new RegExp(
    `[${Object.keys(TRANSLIT).map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("")}`
    + `${Object.keys(TRANSLIT_LETTERS).join("")}]`, "g");

/**
 * Переложить текст в юникод.
 *
 * Замена посимвольная и однопроходная: знаки стоят ПОСЛЕ своей буквы, и
 * комбинирующие знаки юникода стоят там же, поэтому порядок сохраняется сам.
 */
export const translitToUnicode = (raw: string): { text: string; changed: number } => {
    let changed = 0;
    const text = raw.replace(KEYS, (ch) => {
        changed++;
        return TRANSLIT[ch] ?? TRANSLIT_LETTERS[ch] ?? ch;
    });
    return { text: text.normalize("NFC"), changed };
};

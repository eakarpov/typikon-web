// Частная область юникода в церковнославянском наборе — и сведение её к юникоду.
//
// ЧТО ЭТО ТАКОЕ. Шрифты семейства Ponomar (sci.ponomar.net) размещают в области
// частного использования то, чего в юникоде нет отдельным знаком: сложенные
// сочетания звательца с ударением, выносную букву вместе с покрытием, варианты
// начертаний. Набор с ними правилен и в своём шрифте читается — это соглашение,
// а не порча текста.
//
// ЧЕМ ПОДТВЕРЖДЕНЫ ЗНАЧЕНИЯ. Именами глифов самих шрифтов (post-таблицы
// PonomarUnicode, Acathist, Shafarik, Pochaevsk) и сличением начертаний в
// Мономахе — том шрифте, которым набран «Маргарит». Сличение состояло в том,
// что начертание частного кода сравнивалось с начертанием заявленного
// соответствия и, для меры, с заведомо чужим; доля общих пикселей приведена
// в поле `evidence` там, где она что-то доказывает.
//
// ЗАЧЕМ СВОДИТЬ. Частный код держится только на шрифте: за его пределами он
// не отображается и ничему не равен. Наша нормализация написаний
// (@/utils/churchSlavonic) о нём тоже не знает, поэтому слово с «ятью короткой»
// не сводится ни к ѣ, ни к е — и не находится по гражданскому запросу. В
// собрании это 977 знаков в 20 текстах «Маргарита».
//
// ЧЕГО СВЕДЕНИЕ НЕ ДЕЛАЕТ. Сочетания и выносные с покрытием сводятся без потерь:
// это те же знаки, записанные иначе. А варианты начертаний — не то же самое:
// «ять короткая» и «ѣ» отличаются рисунком буквы, и для того, кто воспроизводит
// издание, это различие значимо. Поэтому они сводятся ОТДЕЛЬНЫМ решением, а не
// заодно, и по умолчанию остаются как есть.

export type PuaKind =
    /** Сложенное сочетание надстрочных: сводится без потерь. */
    | "mark"
    /** Выносная буква вместе с покрытием: сводится без потерь. */
    | "superscript"
    /** Вариант начертания буквы: сведение стирает рисунок. */
    | "letter"
    /** Соответствия нет. */
    | "unknown";

export interface PuaEntry {
    cp: number;
    name: string;
    /** Юникодная запись того же самого; пусто — соответствия нет. */
    to?: string;
    kind: PuaKind;
    /** Чем подтверждено значение. */
    evidence: string;
}


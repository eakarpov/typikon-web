export const PUA_BY_CODE: Record<number, PuaEntry> =
    Object.fromEntries(PUA_TABLE.map((e) => [e.cp, e]));

/** Любой знак области частного использования, а не только известный нам. */
export const PUA_PATTERN = /[\u{E000}-\u{F8FF}]|[\u{F0000}-\u{FFFFD}]|[\u{100000}-\u{10FFFD}]/gu;

export interface FoldResult {
    text: string;
    /** Что сведено и сколько раз: код → число. */
    folded: Record<number, number>;
    /** Что оставлено: код → число. Пусто — не осталось ничего. */
    kept: Record<number, number>;
}

export interface FoldOptions {
    /**
     * Сводить и варианты начертаний. По умолчанию нет: «ять короткая» и «ѣ» —
     * не одно и то же для того, кто воспроизводит издание.
     */
    letters?: boolean;
}

/**
 * Сведение частных кодов к юникоду.
 *
 * Возвращает не только текст, но и отчёт: что сведено, что оставлено и сколько
 * раз. Молчаливая правка чужого набора здесь недопустима — читатель должен
 * видеть, чего именно коснулись.
 */
export const foldPua = (text: string, options: FoldOptions = {}): FoldResult => {
    const folded: Record<number, number> = {};
    const kept: Record<number, number> = {};

    const out = text.replace(PUA_PATTERN, (ch) => {
        const cp = ch.codePointAt(0)!;
        const entry = PUA_BY_CODE[cp];
        const foldable = entry?.to && (entry.kind !== "letter" || options.letters);
        if (!foldable) {
            kept[cp] = (kept[cp] ?? 0) + 1;
            return ch;
        }
        folded[cp] = (folded[cp] ?? 0) + 1;
        return entry.to!;
    });

    // NFC в конце — по общему правилу проекта: одно и то же слово не должно
    // лежать в собрании двумя разными строками.
    return { text: out.normalize("NFC"), folded, kept };
};

/** Есть ли в тексте частные коды вообще. */
export const hasPua = (text: string): boolean => {
    PUA_PATTERN.lastIndex = 0;
    return PUA_PATTERN.test(text);
};

// Буквенная цифирь: «ѳ҃і» — 19, «҂аѱѯ҃д» — 1764.
//
// ОДНА ТАБЛИЦА НА ПРОЕКТ. До этого их было две: `VALUES` в @/utils/cyrillicNumeral
// (для румынского набора 1688 года, где цифирью печатаются номера стихов) и
// `DIGITS` в ./hip, и они разошлись ровно так, как расходятся две копии. В обеих
// был мёртвый ключ — «ᲂу» у первой и «и́» у второй: цикл `for (const ch of …)`
// идёт по кодовым точкам, и ключ длиной в две туда не попадает никогда. А ук в
// начертаниях ꙋ и ѹ не знала ни та, ни другая — при том, что ступень hip8 сама
// же производит «ѹ» из «_у», то есть импортёр печатал число, которого потом не
// прочёл бы.
//
// Поведение при этом сведено НЕ БЫЛО, и намеренно: у двух вызывающих разные
// нужды. Румынскому набору нужна строгость (чужая буква — значит это не число,
// и резать текст по нему нельзя), разбору HIP — снисходительность и знак
// тысячи. Сведена таблица, а не решение о том, что считать числом.

/** Значение буквы. Ук во всех начертаниях сводится к «у» до разбора. */
export const NUMERAL_VALUES: Record<string, number> = {
    "а": 1, "в": 2, "г": 3, "д": 4,
    // Пятёрка пишется и є, и е — обе в книгах есть.
    "є": 5, "е": 5,
    "ѕ": 6, "з": 7, "и": 8, "ѳ": 9,
    "і": 10, "к": 20, "л": 30, "м": 40, "н": 50,
    "ѯ": 60,
    // Семьдесят — ѻ (широкое о) и о.
    "ѻ": 70, "о": 70,
    "п": 80, "ч": 90,
    "р": 100, "с": 200, "т": 300,
    // Четыреста — ук; сюда приведены все четыре его написания (см. UK ниже).
    "у": 400,
    "ф": 500, "х": 600, "ѱ": 700, "ѡ": 800, "ц": 900,
};

/** Знак тысячи: множит СЛЕДУЮЩУЮ букву на 1000. */
const THOUSAND = "҂";

// Ук пишется четырьмя способами: диграфом ᲂу (U+1C82 + у), слитно ѹ (U+0479),
// монографом ꙋ (U+A64B) и просто у. Значение у всех одно, и разбирать их по
// отдельности значило бы держать четыре ключа, три из которых однажды забудут.
const UK = /ᲂу|ѹ|ꙋ/g;

// Титло снимаем, знак тысячи оставляем. Диапазоны: U+0300–U+036F — ударения,
// U+0483–U+0489 — титло, покрытие, звательце и прочее ЦС-надстрочное.
const stripMarks = (s: string) =>
    s.normalize("NFD").replace(/[̀-ͯ҃-҉]/g, "").normalize("NFC");

/**
 * Чем опознаётся число.
 *
 * `titlo` — только само титло U+0483 (и знак тысячи, если он разрешён): так
 * спрашивает разбор HIP, где подпись «а҆зъ» со звательцем — слово, а не единица.
 * `marks` — любая из четырёх помет U+0483, U+0484, U+0486, U+0487: так спрашивал
 * румынский набор, и сужать ему признак задним числом нельзя — номера стихов там
 * набраны как набраны.
 */
export type NumeralSign = "titlo" | "marks";

export interface NumeralOptions {
    /** Неизвестная буква — не число вовсе. Иначе она просто пропускается. */
    strict?: boolean;
    /** Знак тысячи ҂ читается, а не отбрасывается. */
    thousands?: boolean;
    sign?: NumeralSign;
}

const SIGNS: Record<NumeralSign, RegExp> = {
    titlo: /҃/,
    marks: /[҃҄҆҇]/,
};

/**
 * Число из цифири; null — если это не цифирь.
 *
 * СУММА, А НЕ ПОЗИЦИЯ. Единицы второго десятка пишутся наоборот («а҃і» — 11,
 * единица перед десяткой), прочие в обычном порядке («к҃а» — 21). Простая сумма
 * верна и там и там, а позиционный разбор только добавил бы способов ошибиться.
 *
 * ПОМЕТА ОБЯЗАТЕЛЬНА. Без неё «ми» — предлог или слог, а не 48.
 */
export const csNumeral = (token: string, options: NumeralOptions = {}): number | null => {
    const { strict = false, thousands = false, sign = "marks" } = options;

    const hasSign = SIGNS[sign].test(token);
    const hasThousand = thousands && token.includes(THOUSAND);
    if (!hasSign && !hasThousand) return null;

    const letters = stripMarks(token)
        .toLowerCase()
        .replace(/[.,:;]/g, "")
        .replace(UK, "у");
    if (!letters) return null;

    let sum = 0;
    let next = 1;
    for (const ch of letters) {
        if (ch === THOUSAND) {
            if (!thousands) {
                if (strict) return null;
                continue;
            }
            next = 1000;
            continue;
        }
        const value = NUMERAL_VALUES[ch];
        if (value === undefined) {
            if (strict) return null;
            continue;
        }
        sum += value * next;
        next = 1;
    }
    return sum || null;
};

// Обратная сторона: буквы по разрядам, старший первым.
const LETTERS: Array<[number, string]> = [
    [900, "ц"], [800, "ѡ"], [700, "ѱ"], [600, "х"], [500, "ф"],
    // Четыреста печатаем монографом ꙋ: в собрании он стоит в 283 текстах против
    // 246 со слитным ѹ и 89 с диграфом ᲂу, и с титлом («ꙋ҃») встречается тоже
    // чаще прочих. Читается всё равно любое написание.
    [400, "ꙋ"],
    [300, "т"], [200, "с"], [100, "р"],
    [90, "ч"], [80, "п"],
    // Семьдесят — широкое ѻ: в собрании «ѻ҃» стоит в 72 текстах против 6 с «о҃».
    [70, "ѻ"],
    [60, "ѯ"], [50, "н"],
    [40, "м"], [30, "л"], [20, "к"], [10, "і"],
    [9, "ѳ"], [8, "и"], [7, "з"], [6, "ѕ"], [5, "є"],
    [4, "д"], [3, "г"], [2, "в"], [1, "а"],
];

const TITLO = "҃";

/** Буквы числа от 1 до 999, без титла и без знака тысячи. */
const letters = (value: number): string => {
    const hundreds = Math.floor(value / 100) * 100;
    const rest = value % 100;
    const head = hundreds ? LETTERS.find(([v]) => v === hundreds)![1] : "";

    // Второй десяток пишется наоборот: «а҃і» — 11, а не «і҃а».
    if (rest >= 11 && rest <= 19) {
        return head + LETTERS.find(([v]) => v === rest - 10)![1] + LETTERS.find(([v]) => v === 10)![1];
    }
    const tens = Math.floor(rest / 10) * 10;
    const units = rest % 10;
    return head
        + (tens ? LETTERS.find(([v]) => v === tens)![1] : "")
        + (units ? LETTERS.find(([v]) => v === units)![1] : "");
};

/**
 * Цифирь из числа: 1764 → «҂аѱѯ҃д».
 *
 * Тысячи — тот же числовой ряд, но перед КАЖДОЙ буквой ставится ҂: 12 000 —
 * «҂і҂в». Титло стоит над второй буквой с конца — так набраны титульные годы
 * Ифики («҂зсо҃в», «҂аѱѯ҃д»), по которым эта запись и выверена; у числа из одной
 * буквы оно стоит над нею самой.
 */
export const toCyrillicNumeral = (value: number): string => {
    if (!Number.isInteger(value) || value < 1) return "";

    const high = Math.floor(value / 1000);
    const low = value % 1000;
    const body = (high ? [...letters(high)].map((c) => THOUSAND + c).join("") : "")
        + (low ? letters(low) : "");

    // Место титла считаем по буквам, а знак тысячи буквой не считается.
    const chars = [...body];
    const letterAt = chars.map((c, i) => (c === THOUSAND ? -1 : i)).filter((i) => i >= 0);
    const at = letterAt[Math.max(0, letterAt.length - 2)];
    return chars.slice(0, at + 1).join("") + TITLO + chars.slice(at + 1).join("");
};

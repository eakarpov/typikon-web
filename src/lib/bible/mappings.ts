// --- Притчи греческого издания: главы 30 и 31 разнесены по книге --------------
//
// Греческие Притчи не знают глав 30 и 31: их содержимое напечатано ВНУТРИ
// двадцать четвёртой и двадцать девятой, вперемежку со своим. Отсюда греческая
// 24-я в 76 стихов против славянских 34, и 29-я в 49 против 27.

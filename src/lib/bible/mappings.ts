const verdictFor = (edition: string, book: string, chapter: number): ChapterVerdict | null =>
    CHAPTER_VERDICTS.find((v) =>
        v.edition === edition && v.book === book
        && (!v.chapters || v.chapters.includes(chapter))) ?? null;

/** Приговор главе: «сверено, сдвига нет», «правилом не выразимо» или ничего. */
export const chapterVerdict = (
    edition: string, book: string, chapter: number,
): "aligned" | "unmappable" | null => verdictFor(edition, book, chapter)?.verdict ?? null;

/** Известно ли, что расхождения этой книги (или главы) правилом не выражаются. */
export const isUnmappable = (edition: string, book: string, chapter?: number): boolean =>
    CHAPTER_VERDICTS.some((v) =>
        v.edition === edition && v.book === book && v.verdict === "unmappable"
        && (!v.chapters || (chapter !== undefined && v.chapters.includes(chapter))));

const matches = (rule: BibleMappingRule, book: string, chapter: number, verse: number): boolean => {
    if (rule.from.book !== book) return false;
    if (rule.from.chapter !== undefined && rule.from.chapter !== chapter) return false;
    if (rule.from.verseFrom !== undefined && verse < rule.from.verseFrom) return false;
    if (rule.from.verseTo !== undefined && verse > rule.from.verseTo) return false;
    return true;
};

/** Правила одного издания — их немного, поэтому просто фильтр без индекса. */
export const mappingsFor = (editionCode: string): BibleMappingRule[] =>
    BIBLE_MAPPINGS.filter((rule) => rule.edition === editionCode);

/**
 * Родная ссылка издания — в каноническую. Без подходящего правила возвращает
 * ту же ссылку: у большинства книг нумерация и есть каноническая.
 *
 * Правила передаются готовым списком, а не берутся по коду издания, чтобы
 * миграция не перебирала их заново на каждом из 73 тысяч стихов.
 */
export const toCanonRef = (
    rules: BibleMappingRule[],
    book: string,
    chapter: number,
    verse: number,
): CanonRef => {
    const rule = rules.find((candidate) => matches(candidate, book, chapter, verse));
    if (!rule) return { canonId: book, chapter, verse };

    return {
        canonId: rule.to.book ?? book,
        chapter: rule.to.chapter ?? chapter,
        verse: verse + (rule.to.verseOffset ?? 0),
    };
};

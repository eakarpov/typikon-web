// Приведение родной нумерации издания к канону.
//
// Издание печатает стихи так, как их разбил его составитель, а зачало устава
// названо по славянской нумерации. Пока обе совпадают, разницы не видно; там,
// где расходятся, нужно правило — иначе чтение молча обрывается на середине.
//
// ЧТО ПРАВИЛА ПОКРЫВАЮТ, А ЧТО НЕТ. Правило выражает СМЕЩЕНИЕ: «эта книга издания
// есть такая-то глава канона», «с такого-то стиха прибавь столько-то». Этого
// хватает, когда издание иначе НАРЕЗАЛО книги, но сами стихи те же. Этого не
// хватает, когда издание иначе РАЗБИЛО текст на стихи: два стиха слиты в один,
// длинный разнесён на три. Такое соответствие правилом не выражается вовсе —
// нужна постишная сверка текстов, которой у нас нет.
//
// Сверка (BIBLE_VERSIFICATION.md, пересобирается
// `npx tsx src/scripts/audit-bible-versification.ts`) показала 246 глав, где длины
// у изданий расходятся, и разброс там от −67 до +35 стихов: у румынской Библии
// 1688 года своя разбивка по всему Ветхому Завету. Поэтому правила заведены только
// там, где соответствие проверено арифметически, а на остальном работает фолбек по
// непокрытию: если издание знает книгу, но отдаёт стихов меньше, чем ожидает
// зачало, чтение целиком берётся из церковнославянского (@/lib/pericopes).
//
// Стих без подходящего правила остаётся в своей нумерации: canonRef = родная
// ссылка. Для церковнославянского издания правил нет вовсе — оно и есть эталон.
//
// ДОПИСАЛ ПРАВИЛО — ПЕРЕСЧИТАЙ КАНОН: `npx tsx src/scripts/recompute-bible-canon.ts`
// (и `--apply`). Правило само по себе ничего не меняет: canonRef лежит у стихов
// посчитанным, и без пересчёта половина книги искалась бы по новому месту, а
// половина по старому.
import { CanonRef } from "@/lib/bible/refs";

export interface BibleMappingRule {
    /** Код издания (bible_editions.code). */
    edition: string;
    /** Что попадает под правило — в РОДНОЙ нумерации издания. */
    from: {
        book: string;
        /** Без главы правило берёт книгу целиком. */
        chapter?: number;
        verseFrom?: number;
        verseTo?: number;
    };
    /** Во что превращается. Незаполненное поле означает «оставить как есть». */
    to: {
        book?: string;
        chapter?: number;
        verseOffset?: number;
    };
    /**
     * Сходится ли соответствие постишно. false означает, что книга и глава верны,
     * а номер стиха внутри может разъехаться, — так помечено то, что проверено и
     * НЕ сошлось, чтобы это не выглядело надёжным.
     */
    exact: boolean;
    note: string;
}


const matches = (rule: BibleMappingRule, book: string, chapter: number, verse: number): boolean => {
    if (rule.from.book !== book) return false;
    if (rule.from.chapter !== undefined && rule.from.chapter !== chapter) return false;
    if (rule.from.verseFrom !== undefined && verse < rule.from.verseFrom) return false;
    if (rule.from.verseTo !== undefined && verse > rule.from.verseTo) return false;
    return true;
};

/** Правила одного издания — их немного, поэтому просто фильтр без индекса. */

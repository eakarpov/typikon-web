// Стихи, которых издание не печатает, хотя канон их держит.
//
// ЗАЧЕМ ПОКАЗЫВАТЬ ТО, ЧЕГО В ИЗДАНИИ НЕТ. Иначе выбравший греческий видит на
// стих меньше, чем сосед со славянским, и решает, что у нас дыра в наборе.
// Молчаливый пропуск и наша недоработка выглядят одинаково — а это разные вещи,
// и различить их читателю нечем. Поэтому стих показывается, но помечается: вот
// что стоит здесь у других, вот почему это издание так не печатает.
//
// ЖИВЁТ КОДОМ, А НЕ В БАЗЕ — по той же причине, что и правила приведения
// (@/lib/bible/mappings): случаев наперечёт, каждый требует объяснения, и правка
// такого рода должна быть видна в истории вместе с тем, кто и зачем её внёс.
// Плюс запись в базе не пережила бы переимпорт издания: он удаляет всё, чего нет
// в источнике, — а этого стиха в источнике как раз и нет.
//
// ТЕКСТ БЕРЁТСЯ У САМОГО ИЗДАНИЯ, где это возможно: тогда мы ничего не
// заимствуем со стороны и не подмешиваем чужую орфографию к своей.

export interface AbsentVerse {
    /** Код издания, которое этот стих не печатает. */
    edition: string;
    canonId: string;
    chapter: number;
    verse: number;
    /** Что здесь стоит по традиции. */
    content: string;
    /** Откуда взят показанный текст — это говорится читателю. */
    supplied: string;
    /** Почему издание его не печатает — это тоже говорится читателю. */
    why: string;
}

export const ABSENT_VERSES: AbsentVerse[] = [
    {
        edition: "grc-lxx-pat",
        canonId: "marka",
        chapter: 7,
        verse: 16,
        // Слово в слово как в Мк. 4:23 этого же издания: «εἴ τις ἔχει ὦτα
        // ἀκούειν, ἀκουέτω.» Тот же оборот стоит и в Мк. 4:9.
        content: "εἴ τις ἔχει ὦτα ἀκούειν, ἀκουέτω.",
        supplied: "текст по Мк. 4:23 этого же издания",
        // Читается как продолжение фразы «этого стиха в издании нет: …», поэтому
        // начинается со строчной и само издание не называет — оно уже названо.
        why:
            "оно правилось по церковным книгам, а лекционарный текст этой фразы не "
            + "знает; Византийский текст большинства её печатает.",
    },
];

/** Есть ли у издания пропуски вообще — чтобы не перебирать таблицу зря. */
const byEdition = new Map<string, AbsentVerse[]>();
ABSENT_VERSES.forEach((item) => {
    const list = byEdition.get(item.edition) ?? [];
    list.push(item);
    byEdition.set(item.edition, list);
});

/** Пропуски издания в одной главе канона. */
export const absentInChapter = (
    editionCode: string | null | undefined,
    canonId: string,
    chapter: number,
): AbsentVerse[] => (byEdition.get(editionCode || "") ?? [])
    .filter((item) => item.canonId === canonId && item.chapter === chapter);

/** Пропуски издания в книге целиком. */
export const absentInBook = (
    editionCode: string | null | undefined,
    canonId: string,
): AbsentVerse[] => (byEdition.get(editionCode || "") ?? [])
    .filter((item) => item.canonId === canonId);

// Имя святого из заголовка святцев.
//
// ЗАЧЕМ ЭТО ВЫВОДИТЬ. Указателя имён у собрания нет: `saints.title` — заголовок,
// а не имя («Никола́й испове́дник, игу́мен Студи́йский», «Бори́с и Гле́б, князья́
// Му́ромские»), и различных заголовков почти столько же, сколько святых. Днеслов
// хранит имена этимологически и по-гречески — «θεοφάνης», «μεθόδιος < μεθόδος», —
// то есть отвечает на другой вопрос. А человеку, ищущему свои именины, нужно
// ровно одно слово: «Николай».
//
// ЭТО НАШ ВЫВОД, А НЕ ДАННЫЕ КНИГИ, и относиться к нему надо соответственно:
// разбор показывается отчётом, ошибается предсказуемо и на странице подписан
// как выведенный. Тем же приёмом живут «наше чтение» в трапезе и догадка о
// престоле в каталоге храмов.
//
// ПРАВИЛО ПРОСТОЕ, И В ЭТОМ ЕГО ДОСТОИНСТВО: имя стоит первым словом заголовка,
// а если первым идёт чин или оборот («евангели́ст Матфе́й», «от 70-ти Алфе́й»,
// «вели́кий кня́зь Андре́й»), — первым после него. Сложное правило здесь было бы
// хуже простого: оно ошибалось бы так же часто, но непонятно где.

/**
 * Снимаем ударение — и только его.
 *
 * Через NFD снимать нельзя: «й» и «ё» разложатся тоже, и Гео́ргий станет
 * «Георгии», а Пётр — «Петр». Оба ушли бы из указателя мимо имени, которое
 * человек набирает. Поэтому разбираем, выбрасываем именно знаки ударения и
 * собираем обратно.
 */
export const stripAccents = (raw: string): string =>
    raw.normalize("NFD")
        // U+0300 гравис, U+0301 акут, U+0311 камора, U+0483 титло, U+0486 звательце
        .replace(/[̀́̑҃҆]/g, "")
        .normalize("NFC");

/**
 * Слова, которыми заголовок начинается ВМЕСТО имени.
 *
 * Список закрытый и снят с данных, а не выдуман: это чины, обороты святцев и
 * счётные слова, стоящие перед именем. Незнакомое слово именем не считается —
 * см. `looksLikeName`, — так что список нужен только для того, чтобы не
 * оборваться на первом же слове и дойти до настоящего имени.
 */
export const NOT_NAMES = new Set([
    "от", "в", "во", "иже", "и", "с", "со", "при",
    "святых", "святый", "святая", "святые", "святаго", "святыя",
    "евангелист", "апостол", "апостолы", "архидиакон", "диакон", "епископ",
    "архиепископ", "митрополит", "патриарх", "игумен", "архимандрит",
    "пресвитер", "иерей", "монах", "инок", "затворник", "столпник",
    "князь", "княгиня", "княжна", "царь", "царица", "царевич", "царевна",
    "великий", "великая", "благоверный", "благоверная",
    "преподобный", "преподобная", "мученик", "мученица", "мученики",
    "священномученик", "великомученик", "великомученица",
    "исповедник", "исповедница", "праведный", "праведная", "блаженный",
    "блаженная", "святитель", "пророк", "пророчица", "целитель",
    "отцы", "отцов", "отец", "богоотцы", "девы", "дева", "жены",
    "собор", "память", "икона", "риза", "обретение", "перенесение",
    "празднование", "чудо", "явление", "положение", "успение",
]);

/** Хвостовые слова: место, прозвание, родство. За ними имён уже не бывает. */
const QUALIFIER = /(ский|ская|ские|ской|цкий|цкая|чудотворец|чудотворца|его|её|ее|их)$/i;

/**
 * Похоже ли слово на имя.
 *
 * Заглавная буква — главный признак: святцы пишут имена с неё, а чины и
 * обороты со строчной. Прочее отсекает очевидное: числа («от 70-ти»),
 * однобуквенное, прозвания по месту («Му́ромские»).
 */
export const looksLikeName = (raw: string): boolean => {
    const word = stripAccents(raw).replace(/[^А-Яа-яЁёІіѢѣ-]/g, "");
    if (word.length < 3) return false;
    if (!/^[А-ЯЁІѢ]/.test(word)) return false;
    if (NOT_NAMES.has(word.toLowerCase())) return false;
    return !QUALIFIER.test(word);
};

/** Слово к виду указателя: без ударений, с большой буквы, «ё» на месте. */
export const normalizeName = (raw: string): string => {
    const word = stripAccents(raw).replace(/[^А-Яа-яЁёІіѢѣ-]/g, "");
    return word ? word[0].toUpperCase() + word.slice(1).toLowerCase() : "";
};

/** Ключ для поиска: по нему сличают набранное человеком с нашим указателем. */
export const nameKey = (raw: string): string =>
    normalizeName(raw).toLowerCase().replace(/ё/g, "е");

export type Confidence = "sure" | "guess";

export interface ExtractedNames {
    names: string[];
    /**
     * `sure` — заголовок об одном лице, имя стоит своим местом.
     * `guess` — соборная память, где имена перечислены вперемешку с чинами и
     * родством («Стефа́н, па́па, Неме́зий ты́сяцкий, Луки́лла до́чь его́»):
     * что-то в этом перечне именем не окажется, и знать об этом надо заранее.
     */
    confidence: Confidence;
    /** Слова, отброшенные перед именем: по ним видно, почему разбор такой. */
    skipped: string[];
}

const words = (title: string): string[] =>
    title.replace(/[()«»„“"]/g, " ").split(/[\s,:;]+/).filter(Boolean);

/**
 * Имена из заголовка.
 *
 * У лица берём первое имя и, если следом идут ещё имена («Андрони́к и Иу́ния»),
 * их тоже: носящий второе имя ищет свои именины ровно так же, как носящий
 * первое. У соборной памяти берём все имена подряд — иначе Евпо́р, помянутый
 * седьмым, не найдёт своего дня вовсе.
 */
export const namesOf = (title: string | null | undefined, type?: string | null): ExtractedNames => {
    const empty: ExtractedNames = { names: [], confidence: "sure", skipped: [] };
    if (!title) return empty;

    const list = words(title);
    const council = type === "Council";
    const skipped: string[] = [];
    const names: string[] = [];

    // Союз между именами — не конец перечня, а его продолжение: «Андрони́к И
    // Иу́ния» это два имени, а не одно и обрыв.
    const connector = (word: string) => /^(и|да|или)$/i.test(stripAccents(word));

    // «иже в Кри́те: Феодул…» — слово после предлога это МЕСТО, а не имя, и
    // пишется оно с заглавной ровно как имя. Отличить их можно только по
    // предлогу, стоящему перед.
    const afterPreposition = (i: number) =>
        i > 0 && /^(в|во|на|при|из|от)$/i.test(stripAccents(list[i - 1]));

    for (let i = 0; i < list.length; i++) {
        const word = list[i];
        if (names.length && connector(word)) continue;
        if (afterPreposition(i)) { if (!names.length) skipped.push(word); continue; }
        if (looksLikeName(word)) {
            const name = normalizeName(word);
            if (name && !names.includes(name)) names.push(name);
            // У лица имена идут подряд в начале: встретив после них слово,
            // именем не являющееся, дальше не идём — там прозвания и место.
            if (!council) {
                const next = list[i + 1];
                if (next && !looksLikeName(next) && !connector(next)) break;
            }
            continue;
        }
        if (!names.length) skipped.push(word);
        // Соборную память идём до конца: имена в ней рассыпаны по всей строке.
        else if (!council) break;
    }

    return { names, confidence: council ? "guess" : "sure", skipped };
};

import type { Genre } from "@/lib/accents/mark";

// КАКОГО РОДА ТЕКСТ — чтение или песнопение.
//
// От этого зависит, по какому собранию считать ударение: «спасе́» — аорист
// чтений, «спа́се» — звательный песнопений, и складывать их частоты нельзя
// (словарь предупреждает об этом сам, в описании `/api/v2/accents`).
//
// Замерено на тринадцати службах из тех семидесяти трёх, что размечены не
// полностью: из 9392 слов под знаком род меняет 382, и меняет к лучшему —
//
//   * 209 пишутся тем знаком, каким пишут певческие книги (оксия вместо варии
//     на конце слова: «твою́», а не «твою̀»);
//   * 132 спорных становятся решёнными, и лишь 37 наоборот;
//   * 4 ударения переезжают на другой слог — это настоящие омографы.
//
// **Решает книга, а не род текста.** У текстов есть поле `type`, но оно про иное:
// службы лежат в нём как `Teaching`, наравне с беседами Златоуста. А вот книга
// «Службы» — это ровно гимнография и есть.
//
// **По имени книги, потому что другого признака нет.** У книг нет поля рода:
// есть имя, язык и порядок. Имя — вещь правимая, и однажды это подведёт; правильнее
// было бы завести книгам род, и тогда этот список станет не нужен. Пока же он
// здесь, в одном месте, а не размазан по вызовам `markText`.

/** Книги, чьи тексты поются, а не читаются. */
const HYMNOGRAPHY: ReadonlySet<string> = new Set([
    "Службы",
]);

/**
 * Род текста по имени его книги. Не знаем книги — считаем чтением: это и
 * умолчание разметчика, и верно для подавляющего большинства корпуса.
 */
export const genreOfBook = (bookName: string | null | undefined): Genre =>
    HYMNOGRAPHY.has((bookName ?? "").trim()) ? "chant" : "reading";

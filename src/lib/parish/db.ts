import clientPromise from "@/lib/mongodb";

// ГДЕ ЛЕЖИТ ПРИХОДСКОЕ — и почему не там же, где корпус.
//
// В `typikon` лежит то, что делаем МЫ: тексты, дни, святцы, храмы. Эта база
// целиком пересобирается у нас и целиком уезжает на сервер (`release-db.sh`,
// `mongorestore --drop`) — накатывается поверх, а не сливается.
//
// Приходское же наполняется НА ПРОДЕ и не нами: часовой пояс и правила прихода,
// расписание, заявки на ведение, права ответственных. Локально всего этого нет
// и быть не может. Пока оно лежало в `typikon`, каждая выкладка везла на сервер
// пустые коллекции, и `--drop` стирал приходам то, что они сами о себе сказали.
//
// Оттого — в `typikon-users`, рядом с пользователями и их заметками, по той же
// причине, по какой отдельно живут новости: выкладка корпуса туда не заглядывает
// вовсе, и стирать оттуда нечем. Заодно это и правда пользовательские данные —
// персональные в том числе, — и держать их вместе с достоянием проекта незачем.
//
// Переезд с прежнего места: `npm run parish:move`.
export const parishDb = async () => (await clientPromise).db("typikon-users");

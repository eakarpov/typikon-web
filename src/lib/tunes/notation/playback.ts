// «Послушать» — перевод разобранного напева в тоны для звукового движка браузера.
//
// ЧЕМ ЗДЕСЬ НЕ ПОЛЬЗУЕМСЯ И ПОЧЕМУ. У abcjs есть свой проигрыватель, и он
// хорош, но звучит он сэмплами: на каждую ноту тянет из чужого хранилища
// (paulrosen.github.io) отдельный mp3. Это чужой сервер на каждое нажатие,
// мегабайты в офлайне, которого у нас как раз нет, и вопрос о правах на чужие
// записи — ради того, чтобы напев прозвучал роялем. Роялем он звучать не должен.
//
// Поэтому берём у abcjs только РАЗБОР (`visualObj.setUpAudio()` отдаёт голоса
// нотами с высотой, началом и длительностью — без единого обращения наружу), а
// звук делаем сами чистым тоном. Тон — не голос: он не читает богослужебный
// текст и не притворяется хором, а показывает высоту и ход, как камертон. Это
// ровно то, чего ждут от строки напева: «как это поётся».
//
// Здесь только арифметика — ни браузера, ни звука, и потому она проверяема
// тестом (playback.test.ts).

/** Нота, как её отдаёт разбор abcjs: доли ЦЕЛОЙ ноты, а не секунды. */
export interface AudioNote {
    pitch: number;
    start: number;
    duration: number;
    volume?: number;
}

export interface Tone {
    hz: number;
    /** Секунды от начала проигрывания. */
    at: number;
    till: number;
    /** Громкость 0..1 — уже поделённая между голосами. */
    gain: number;
}

/** Строй равномерно темперированный, ля первой октавы — 440 Гц. */
export const midiToHz = (pitch: number): number => 440 * Math.pow(2, (pitch - 69) / 12);

/**
 * Зазор между нотами, секунды.
 *
 * НЕ УКРАШЕНИЕ, А УСЛОВИЕ РАЗБОРЧИВОСТИ. Распев поётся речитативом: подряд
 * идёт по восемь-десять нот ОДНОЙ высоты, по слогу на ноту. Без зазора
 * соседние тоны одной высоты сливаются в один длинный гудок, и услышать, что
 * их восемь, нельзя. Зазор возвращает каждой ноте свой приступ.
 */
const GAP_SEC = 0.055;

/** Короткую ноту зазор не должен съедать больше чем наполовину. */
const MIN_SOUNDING = 0.5;

/**
 * Сколько секунд длится ЦЕЛАЯ нота при этом темпе.
 *
 * `qpm` — четвертей в минуту, как принято в нотной записи и как его понимает
 * abcjs; доли у него считаются от целой, отсюда четвёрка.
 */
export const wholeNoteSec = (qpm: number): number => (4 * 60) / qpm;

/**
 * Голоса — в тоны, по порядку звучания.
 *
 * Громкость делится между голосами: четыре партии, сложенные в полную силу,
 * дают перегруз, и вместо аккорда слышен треск.
 */
export const tonesOf = (tracks: AudioNote[][], qpm: number): Tone[] => {
    const sounding = tracks.filter(track => track.length > 0);
    if (!sounding.length || qpm <= 0) return [];

    const whole = wholeNoteSec(qpm);
    const share = 1 / Math.sqrt(sounding.length);

    const tones = sounding.flatMap(track => track.map((note) => {
        const at = note.start * whole;
        const full = note.duration * whole;
        const till = at + Math.max(full * MIN_SOUNDING, full - GAP_SEC);
        return {
            hz: midiToHz(note.pitch),
            at,
            till,
            gain: ((note.volume ?? 96) / 127) * share,
        };
    }));

    return tones.sort((a, b) => a.at - b.at || a.hz - b.hz);
};

/** Сколько длится всё вместе, секунды: по последней отзвучавшей ноте. */
export const lengthSec = (tones: Tone[]): number =>
    tones.reduce((longest, tone) => Math.max(longest, tone.till), 0);

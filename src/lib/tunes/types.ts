// Напевы: чем поётся песнопение и как эту мелодию записывают.
//
// Три сущности, намеренно не слитые в одну, потому что меняются они порознь.
//
// ТРАДИЦИЯ — кто и как поёт: знаменный распев малый, обиход партесный. Она же
// говорит, сколько в ней голосов и в каких нотациях она вообще записывается:
// партесное многоголосие крюками не пишется, и предлагать для него крюковую
// запись было бы обманом.
//
// НАПЕВ — мелодия, адресуемая СЕЛЕКТОРОМ. Селектора два рода, и оба настоящие:
// гласовый напев выбирается парой «глас + жанр» (в партесе тропарь, стихира и
// ирмос одного гласа поются РАЗНЫМИ напевами), подобен — своим зачином. Сверх
// того у напева бывает ЛОКАЛИЗАЦИЯ: один и тот же подобен на Валааме и в
// Оптиной поют не совсем одинаково. Локализация — уточнение, а не отдельная
// традиция, поэтому при её отсутствии берётся общий напев (см. resolve.ts).
//
// ЗАПИСЬ — тот же напев, положенный в конкретную нотацию: крюки, линейные
// ноты, со временем невмы. Записей у напева несколько, и это не варианты
// мелодии, а варианты ПИСЬМА одной мелодии; в партесе к ним добавляется голос.
//
// Ключевое следствие деления: СТРОЕНИЕ напева (сколько шагов, какой из них
// растяжимый, на какой обязан прийтись ударный слог) лежит на напеве, а не на
// записи. Так крюковая и линейная записи одной стихиры не могут разойтись в
// раскладке по слогам — а разойдись они, читатель увидел бы два разных деления
// текста и не узнал бы, которое верно.

/** Нотации, в которых мы умеем показывать напев. */
export type Notation = "znamenny" | "staff";

/**
 * Голос. Единогласие — не «первый голос из одного», а отсутствие деления:
 * знаменный распев поётся в унисон, и приписывать ему партию дисканта нельзя.
 */
export type Voice = "edinoglas" | "soprano" | "alt" | "tenor" | "bas";

export interface Tradition {
    id: string;
    title: string;
    /** Пояснение, откуда традиция и чем отличается: показывается при выборе. */
    note?: string;
    voices: Voice[];
    notations: Notation[];
}

/** Местный извод: монастырь, епархия, приход. Всегда при своей традиции. */
export interface Locality {
    id: string;
    traditionId: string;
    title: string;
}

/**
 * Чем напев выбирается.
 *
 * tone + genre — гласовый напев. genre — это `content_items.content_unit`
 * корпуса (stichera, troparion, irmos…), взятый как есть: другого имени у
 * рода песнопения у нас нет, и заводить второе значило бы держать таблицу
 * соответствий, которая разойдётся с корпусом на первой же новой книге.
 *
 * podoben — подобен, опознаваемый по зачину. Зачин в корпусе напечатан с
 * ударениями («До́ме Евфра́фов»), поэтому сличается он нормализованным
 * (см. podobenKey в resolve.ts). Глас при подобне обязателен: «Яви́лся еси́»
 * стоит в корпусе при разных гласах, и без гласа это разные напевы под одним
 * именем.
 */
export type Selector =
    | { kind: "tone"; tone: number; genre: string }
    | { kind: "podoben"; podoben: string; tone: number };

/**
 * Шаг напева — ОДИН СЛОГ. Строение без содержания: что именно здесь поётся,
 * знает запись, а шаг знает только, как он ложится на текст.
 *
 * Шаг — это слог, а не нота. Распев (несколько нот на одном слоге) живёт внутри
 * содержания записи: «Пло́ ___ тию» — это один шаг, у которого в линейной записи
 * стоит «A G F», а в крюковой одно знамя. Держи мы шаг за ноту, распев пришлось
 * бы размазывать по слогам, которых под ним нет.
 *
 * flex — ЧИТОК: на нём вычитывается сколько угодно слогов, в том числе ни
 * одного. В группе он один: двух растяжимых мест не бывает, и будь их два,
 * раскладка стала бы неоднозначной. В нотном обиходе читок помечен штрихом на
 * ноте.
 *
 * stress — шаг, привязанный к УДАРНОМУ СЛОГУ СВОЕЙ ГРУППЫ. Их два рода:
 *
 *   "first" — распев на ПЕРВОМ ударном («и вос-кре́с-ша…»);
 *   "last"  — распев на ПОСЛЕДНЕМ («…нас ра́ди»).
 *
 * Этим напев и держится за текст, а разница между родами — с какого конца
 * группа ищет своё ударение: «first» отсчитывается слева, «last» справа.
 * Поэтому у заключительного колена третьего гласа обе группы «last» садятся на
 * два последних ударных слога — «ве́лию» и «ми́лость», — и порядок не путается.
 */
export interface Step {
    flex?: boolean;
    stress?: "first" | "last";
}

/**
 * РАСПЕВНЫЕ ГРУППЫ отдельной пометки не требуют: группу начинает сам шаг с
 * распевом, а шаги до первого распева — предраспев (слоги, какие поются, но в
 * группу не входят: «и вос-» перед «кре́сша»).
 *
 * Правило выведено из книг, а не придумано: обиход помечает начала групп
 * стрелками, и все три разобранных колена ложатся на него без натяжек —
 * «Пло́тию … нас ра́ди» (две группы), «и вос-кре́сша из ме́ртвых» (предраспев и
 * две группы), «и подаде мирови ве́лию ми́лость» (читок в предраспеве и две
 * группы подряд). Отдельная пометка была бы четвёртым способом сказать то же
 * самое и разошлась бы с распевами при первой же правке.
 *
 * Групп в колене бывает до двух; больше модель тоже стерпит, но такого в
 * разобранных гласах не встретилось.
 */

/**
 * Строка напева — мелодия одного колена.
 *
 * Строк у напева столько, сколько их в мелодии, и это не украшение модели.
 * Гласовый напев обходится тремя (зачин, вычитывание, исход), а подобен —
 * нет: «До́ме Евфра́фов» это пять строк, у каждой своя мелодия, и свести их к
 * «обычной» и «последней» значило бы спеть подобен неверно. Проверено по
 * корпусу: этим подобном подписаны 268 групп, и все они на пять колен.
 */
export interface TuneLine {
    /** Как строка зовётся у певчих: «зачин», «медианта», «исход». */
    label?: string;
    steps: Step[];
}

/**
 * ПОРЯДОК СТРОК — в каком они поются и что повторяется.
 *
 * Списками НОМЕРОВ, а не устройством самого списка строк, и это третья по счёту
 * правка модели, каждый раз от настоящих данных.
 *
 * Обиход печатает порядок прямо под схемой, и печатает его по-разному:
 * глас 1 стихирный — «‖: 1, 2, 3, 4 :‖ закл.», глас 3 тропарный — «1, 3,
 * ‖: 1, 2, 3 :‖ закл.». Во втором строки идут НЕ ПОДРЯД: первая и третья
 * поются зачином, а потом первая же возвращается в круг. Промежутком
 * «повторять со второй по четвёртую» такое не выразить, а выписать строки
 * подряд списком значило бы держать две копии первой строки — и они разошлись
 * бы при первой правке.
 *
 * head — строки до знака повтора, по разу; cycle — под знаком повтора, идут по
 * кругу, сколько нужно; tail — после, по разу. Пустой cycle означает напев
 * фиксированной длины: так устроен подобен, и лишние колена ему не по мерке —
 * об этом надо сказать, а не сгладить (см. apply.ts).
 */
export interface LineOrder {
    head: number[];
    cycle: number[];
    tail: number[];
}

/**
 * ВАРИАНТ СТРОКИ — то же место в напеве, спетое иначе.
 *
 * Третий род различия, и он не сводится к двум прежним. Традиция — это кто
 * поёт, извод — где поют, а вариант фразы одинаково распространён в ОДНОЙ
 * традиции: обиход глас 1 стихирный печатает варианты первой и четвёртой
 * строк вертикальными стрелками и оговаривает, что оба в московской традиции
 * равно ходовы. Ни своей традицией, ни изводом такое не назовёшь — соврали бы
 * и о том, и о другом.
 *
 * Вариант заменяет ОДНУ строку, а не напев целиком: остальные четыре поются
 * как были. Поэтому он лежит отдельным списком, а не вторым напевом — иначе
 * общие строки пришлось бы дублировать, и при первой же правке они разошлись
 * бы молча.
 */
export interface LineVariant {
    id: string;
    /** Номер заменяемой строки. */
    line: number;
    label: string;
    steps: Step[];
}

/**
 * Содержание записи: строки и шаги, один в один со строками напева.
 * Что лежит в ячейке, решает нотация — для крюков это знамя (символы блока
 * U+1CF00), для линейной записи фрагмент ABC («G», «A2», «GA»).
 */
export type ScoreLines = string[][];

export interface Score {
    notation: Notation;
    voice: Voice;
    /** Откуда взята запись: издание, рукопись, обиход прихода. */
    source?: string;
    /** Тональность линейной записи; для крюков не значит ничего. */
    key?: string;
    lines: ScoreLines;
    /** Содержание вариантов строк, по ключу варианта. Длина — как у его шагов. */
    variants?: Record<string, string[]>;
}

export interface Tune {
    id: string;
    traditionId: string;
    /** null — общий напев традиции; иначе местный извод. */
    locality: string | null;
    title: string;
    select: Selector;
    lines: TuneLine[];
    /** Порядок строк — тот самый, что книга печатает под схемой. */
    order: LineOrder;
    /**
     * ОБРАЗЕЦ — тот текст, на котором напев напечатан в книге, с коленами,
     * размеченными как там.
     *
     * Нужен, чтобы напев было на чём сверить. Корпус размечает колена не
     * везде, и того самого песнопения, под которым напечатана схема, в нём
     * может не оказаться размеченным вовсе — как случилось с тропарём третьего
     * гласа. Тогда проверить напев не на чем, а проверять его надо: ноты сняты
     * руками.
     */
    sample?: { text: string; note?: string };
    /** Варианты отдельных строк. Пусто — вариантов нет, и это обычное дело. */
    variants?: LineVariant[];
    scores: Score[];
}


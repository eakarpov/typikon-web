// Здоровье собрания: чего в нём недостаёт, числами.
//
// Панель заведена не ради красоты отчёта, а ради двух вещей сразу. Первая —
// показать свои дыры прежде, чем их найдёт читатель: собрание, которое молчит
// о недоделанном, читается как законченное, и всякая пустая страница тогда
// выглядит поломкой, а не начатой работой. Вторая — сделать эти дыры
// перечислимыми: пока «надо бы доразметить каноны» остаётся словами, за них
// нельзя взяться; «3 133 канона из 3 408 без роли» — уже задача.
//
// ВСЯКИЙ ПОКАЗАТЕЛЬ — НЕДОСТАЧА, А НЕ ОХВАТ. Считать можно и так и так, но
// сделанное на такой странице не нужно никому: она открывается, чтобы найти
// работу. Оттого у всех строк один знак — сколько ещё не сделано, — и их можно
// сравнивать между собой, не читая каждую подпись.
//
// ЧИСЛО БЕЗ ОБЪЯСНЕНИЯ ЗДЕСЬ БЕСПОЛЕЗНО. У каждой строки есть `note`: что эта
// недостача значит и чем она грозит. «27 ссылок на ирмос не сошлись» ничего не
// говорит тому, кто не разбирал Ирмологий, а «книга печатает ирмос зачином, и
// эти зачины не нашли своего полного текста» — говорит.

/** Одна недостача: сколько не сделано, из скольких и что это значит. */
export interface Metric {
    id: string;
    label: string;
    /** Сколько ещё не сделано. */
    gap: number;
    /** Из скольких всего; null — знаменателя нет и доли не будет. */
    total: number | null;
    /** Что это значит и чем грозит. Без этого строка бесполезна. */
    note: string;
    /** Куда идти, чтобы это увидеть или починить. */
    href?: string;
    /** Недостача, которую закрывают не правкой, а разбором книг. */
    manual?: boolean;
    /**
     * Не работа, а наблюдение.
     *
     * «Стихи канона, которых службы не касаются» — четыре пятых Писания, и
     * покрась мы эту строку как недостачу, она стала бы самой тревожной на
     * странице. Между тем закрывать её нечем и незачем: службы и не должны
     * пропеть Писание целиком. Такие строки стоят здесь ради числа рядом с
     * прочими и меряются иначе.
     */
    observation?: boolean;
}

export interface MetricGroup {
    id: string;
    title: string;
    /** Откуда числа: корпус, Монга, словарь. Чтобы знать, чем их проверить. */
    source: string;
    metrics: Metric[];
    /** Источник недоступен — не ноль, а «спросить не у кого». */
    unavailable?: string;
}

export interface HealthReport {
    groups: MetricGroup[];
    generatedAt: string;
    /** Предыдущий снимок, если он есть: с чем сравнивать. */
    previous?: HealthSnapshot | null;
}

/** Снимок для сравнения во времени: только числа, без подписей. */
export interface HealthSnapshot {
    takenAt: string;
    gaps: Record<string, number>;
}

/** Доля недостачи в процентах; null — знаменателя нет. */
export const gapShare = (metric: Metric): number | null => {
    if (!metric.total || metric.total <= 0) return null;
    return Math.round((metric.gap / metric.total) * 1000) / 10;
};

/**
 * Насколько всё плохо — три ступени, и они не про важность, а про долю.
 *
 * Цвет на такой странице читают раньше числа, и соблазн красить по важности
 * велик: «памяти без святого» ведь нужнее, чем «ссылки на ирмос». Но важность
 * — суждение, и меняется оно от того, чем сейчас занят проект, а доля — факт.
 * Поэтому красим долей, а важность оставляем порядку строк.
 */
export type Severity = "low" | "mid" | "high";

export const severityOf = (metric: Metric): Severity => {
    // Наблюдение не бывает тревожным: его не закрывают.
    if (metric.observation) return "low";
    const share = gapShare(metric);
    // Без знаменателя судить не о чем: одна недостача из неизвестно скольких
    // не хуже и не лучше другой.
    if (share === null) return "mid";
    if (share >= 50) return "high";
    if (share >= 10) return "mid";
    return "low";
};

/**
 * Что изменилось со снимка: положительное число — недостача выросла.
 *
 * Знак выбран так нарочно. Панель показывает недостачи, и «+12» здесь значит
 * «стало хуже на двенадцать»; обратный знак пришлось бы всякий раз читать
 * через отрицание.
 */
export const changeSince = (
    metric: Metric, previous: HealthSnapshot | null | undefined,
): number | null => {
    if (!previous) return null;
    const was = previous.gaps[metric.id];
    if (was === undefined) return null;
    return metric.gap - was;
};

/** Снимок из отчёта: только числа, чтобы сравнивать снимки между собой. */
export const snapshotOf = (report: HealthReport): HealthSnapshot => ({
    takenAt: report.generatedAt,
    gaps: Object.fromEntries(
        report.groups.flatMap((group) => group.metrics.map((m) => [m.id, m.gap])),
    ),
});

import {
    LEGACY_SHUTDOWN_HTTP, LEGACY_SHUTDOWN_ISO, LEGACY_SHUTDOWN_LABEL, SITE_HOST, SITE_URL,
} from "@/utils/site";
import type { AllDayEvent } from "@/lib/ical";

// Что мы говорим о переезде — в одном месте, чтобы четыре канала говорили одно
// и то же. Меняется срок или формулировка — меняется здесь.
//
// ВСЁ В ЭТОМ ФАЙЛЕ ВРЕМЕННОЕ. После отключения старого адреса (середина января)
// модуль удаляется целиком вместе с его вызовами: полосой в рамке, полосой на
// сайте, заголовками Sunset и событием в лентах.
//
// Каналов четыре, потому что четыре рода людей, и до каждого достаёт только своё:
//
//   * читатель сайта — полосой наверху страницы;
//   * приход с рамкой на своём сайте — полосой внутри рамки: другого способа
//     показать что-либо хозяину чужой страницы у нас нет;
//   * подписчик ленты — событием В САМОЙ ЛЕНТЕ: почты его мы не знаем, и это
//     единственная дверь;
//   * чужая программа с ключом — заголовками ответа, которые для того и
//     стандартизованы.

/** Полоса на странице и в рамке. Одна фраза: место в рамке считанные пиксели. */
export const MIGRATION_NOTICE = `Сайт переехал на ${SITE_HOST} — старый адрес отключается ${LEGACY_SHUTDOWN_LABEL}.`;

export const MIGRATION_URL = SITE_URL;

/**
 * Заголовки для чужих программ. `Sunset` описан в RFC 8594 и говорит, когда
 * адрес перестанет отвечать; `Link` с successor-version ведёт на замену. Приём
 * уже отработан на первой версии API (`lib/api/v1Deprecation`) — здесь то же
 * самое, но про адрес, а не про версию.
 */
export const legacyHostHeaders = (): Record<string, string> => ({
    Sunset: LEGACY_SHUTDOWN_HTTP,
    Link: `<${SITE_URL}>; rel="successor-version"`,
    // Нестандартный, зато видимый глазами в консоли и в журнале клиента.
    //
    // ТОЛЬКО ЛАТИНИЦА, И ЭТО НЕ ВКУСОВЩИНА: значение заголовка — ByteString,
    // всё выше 255 в него не лезет. Первая же попытка положить сюда русскую
    // фразу уронила КАЖДЫЙ запрос к API со старого адреса пятисотой ошибкой:
    // заголовки ставятся до тела, и падает не текст, а весь ответ.
    "X-Typikon-Notice":
        `moved to ${SITE_HOST}; this host shuts down ${LEGACY_SHUTDOWN_ISO}`,
});

/**
 * Событие о переезде для подписных лент.
 *
 * Идёт во ВСЕ ленты, а не только в отдаваемые со старого адреса, и это осознанно.
 * Лента может отдаваться статически, одним телом на оба адреса; делать её
 * зависящей от хоста значило бы пересчитывать сотню дней на каждый запрос ради
 * одной строки. Подписавшийся уже на новый адрес увидит одно лишнее событие и
 * поймёт его — а подписчик старого адреса иначе не узнает ничего.
 *
 * Дата — день отключения: событие должно лежать впереди, там, куда человек
 * заглядывает, а не теряться в прошедших днях.
 */
export const migrationEvent = (): AllDayEvent => ({
    // UID постоянный: событие правится, а не заводится заново при каждой сборке
    // ленты, иначе у подписчика их накопится столько, сколько раз он обновился.
    uid: `pereezd-2027-01@${SITE_HOST}`,
    date: "20270115",
    summary: `Уставные чтения переехали на ${SITE_HOST}`,
    description:
        `Сайт и все ленты переехали на ${SITE_HOST}. Если вы подписались по старому адресу `
        + `(typikon.su), подпишитесь заново: ${SITE_URL}/calendar — старый адрес отключается `
        + `${LEGACY_SHUTDOWN_LABEL}, и лента просто перестанет обновляться.`,
    url: `${SITE_URL}/calendar`,
});

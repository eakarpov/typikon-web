//
// СПРАШИВАЕТСЯ ВОЗМОЖНОСТЬ, А НЕ РОЛЬ. Код нигде не спрашивает «админ ли он»:
// он спрашивает «может ли он разбирать заявки». Иначе всякая новая роль
// заставляла бы править условия по всему проекту, и рано или поздно где-то
// осталось бы старое.
//
// РОЛЬ — ЭТО СВЯЗКА ВОЗМОЖНОСТЕЙ, и живёт она здесь, а не в базе: список
// невелик, меняется правкой кода, и держать его записями значило бы завести
// вторую правду о том, кому что можно.
//
// ПРАВО НА ПРИХОД СЮДА НЕ ВХОДИТ. Оно ИМЕННОЕ и на один храм (parish/access),
// принадлежит приходу, а не сайту, и раздаёт его приход. Здесь только то, что
// сайт вправе дать от себя.

export const CAPABILITIES = {
    /** Править разделы админки: тексты, книги, дни, новости. */
    "content": "править содержимое сайта",
    /** Разбирать заявки на ведение приходского расписания. */
    "parish.claims": "разбирать заявки приходов",
    /** Назначить ответственного за расписание руками, по разговору. */
    "parish.grant": "назначать ответственных за расписание",
    /** Раздавать права другим. */
    "roles.grant": "раздавать права",
} as const;

export type Capability = keyof typeof CAPABILITIES;

export interface Role {
    key: string;
    label: string;
    note: string;
    /** `"*"` — всё, что есть и что появится. */
    caps: Capability[] | "*";
}

export const ROLES: Record<string, Role> = {
    admin: {
        key: "admin",
        label: "Администратор",
        note: "Может всё, включая то, что появится завтра.",
        caps: "*",
    },
    "parish-moderator": {
        key: "parish-moderator",
        label: "Модератор приходов",
        note: "Разбирает заявки на ведение расписания и назначает ответственных. "
            + "В разбор книг не входит вовсе.",
        caps: ["parish.claims", "parish.grant"],
    },
};

export interface UserLike {
    roles?: string[] | null;
    /** Прежний единственный маркер. Читается, но больше не ставится. */
    isAdmin?: boolean | null;
}

/**
 * Возможности пользователя.
 *
 * Прежний `isAdmin` читается наравне с ролями и значит «администратор»: базу
 * переписывать ради этого незачем, а забыть перевести кого-то одного —
 * значит запереть человека снаружи. Ставить его новым больше нельзя, и
 * скрипт `roles` переведёт старых, когда до них дойдут руки.
 */
export const capsOf = (user: UserLike | null | undefined): Set<Capability> => {
    const out = new Set<Capability>();
    if (!user) return out;
    const roles = [...(user.roles ?? [])];
    if (user.isAdmin && !roles.includes("admin")) roles.push("admin");
    for (const key of roles) {
        const role = ROLES[key];
        if (!role) continue;   // роль из базы, которой в коде нет, — просто нет
        if (role.caps === "*") {
            for (const c of Object.keys(CAPABILITIES) as Capability[]) out.add(c);
        } else {
            for (const c of role.caps) out.add(c);
        }
    }
    return out;
};

export const userCan = (user: UserLike | null | undefined, cap: Capability) =>
    capsOf(user).has(cap);

export const roleLabels = (roles: string[] | null | undefined) =>
    (roles ?? []).map(r => ROLES[r]?.label ?? r);

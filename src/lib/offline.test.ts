import { strict as assert } from "node:assert";
import { describe, it } from "node:test";
import { formatBytes, plural } from "./offline";

// Числительные и размеры показываются человеку, а не машине: «2 страниц»
// и «1.7 МБ» — это ошибки, которые видит каждый, кто открыл настройки.
describe("счёт страниц", () => {
    it("склоняет по последней цифре", () => {
        const forms = [1, 2, 5, 21, 22, 25]
            .map((n) => plural(n, "страница", "страницы", "страниц"));
        assert.deepEqual(forms, [
            "страница", "страницы", "страниц",
            "страница", "страницы", "страниц",
        ]);
    });

    it("держит одиннадцать-четырнадцать на последней форме", () => {
        const forms = [11, 12, 14, 111, 112]
            .map((n) => plural(n, "страница", "страницы", "страниц"));
        assert.deepEqual(forms, ["страниц", "страниц", "страниц", "страниц", "страниц"]);
    });

    it("считает ноль по последней форме", () => {
        assert.equal(plural(0, "страница", "страницы", "страниц"), "страниц");
    });
});

describe("размер занятого", () => {
    it("растёт от байтов к мегабайтам", () => {
        assert.equal(formatBytes(512), "512 Б");
        assert.equal(formatBytes(2048), "2 КБ");
        assert.equal(formatBytes(1024 * 1024 * 1.75), "1,8 МБ");
    });

    it("отделяет дробную часть запятой, а не точкой", () => {
        assert.ok(!formatBytes(1024 * 1024 * 3.5).includes("."));
    });
});

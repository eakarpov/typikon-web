// Пять полей-подборщиков в редакторе персоны (род, персона, государство,
// национальность, правление) устроены одинаково: показывают выбранное, ищут по
// своей таблице и возвращают наверх идентификатор. Договор у них один, и
// описан он здесь один раз.
export interface PickerProps {
    /** Выбранный идентификатор; пустая строка в редакторе значит «не выбрано». */
    value: number | string | null;
    /** null — снятый выбор: крестик рядом с выбранным. */
    setValue: (id: number | null) => void;
    placeholder: string;
}

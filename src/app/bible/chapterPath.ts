// Куда вести, когда читатель сменил базу или снял ведущее издание.
//
// Смена базы уводит на первую главу: у изданий разное число глав (у греческих
// Притчей 29, у славянских 31), и остаться на прежнем номере значило бы иногда
// упираться в главу, которой у новой базы нет.
//
// НО УВОДИТЬ ЕСТЬ КУДА НЕ ВСЕГДА. Оглавление Библии — тоже страница с выбором
// изданий, а главы у неё нет. Слепая замена последнего куска пути превращала
// там «/bible» в «/1» — адрес, которого не существует, и переключатель счёта
// уводил читателя на 404. Поэтому номер главы подставляется только в путь,
// который и правда ведёт к главе.
const CHAPTER_PATH = /^(\/bible\/[^/]+)\/\d+$/;

/** Путь той же книги, но другой главы. Не путь главы — возвращается как есть. */
export const chapterPath = (pathname: string, chapter: number): string => {
    const m = CHAPTER_PATH.exec(pathname);
    return m ? `${m[1]}/${chapter}` : pathname;
};

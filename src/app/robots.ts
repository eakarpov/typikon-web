import { MetadataRoute } from "next";

// Правила обхода. Лежат в коде рядом с картой сайта (sitemap.ts), а не статикой в
// public/, по той же причине: адреса разделов меняются, и правило, которое живёт
// отдельным файлом, устаревает молча.
//
// Заведомо слабое место robots.txt в том, что это просьба, а не запрет: её
// соблюдают поисковики, которые нам и нужны, и не соблюдают ровно те обходчики,
// от которых нагрузка. Поэтому файл решает первую половину задачи — не пускать
// добросовестного робота туда, где ему нечего делать и где каждый запрос дорог, —
// а вторая половина (счётчики и отказы тем, кто просьбу не читает) живёт в
// rateLimit.ts и в настройках nginx.

const BASE_URL = "https://www.typikon.su";

/** Личное и служебное: индексировать нечего, а отвечает всё это из базы. */
const PRIVATE = [
    "/admin",
    "/profile",
    "/settings",
    "/notes",
    "/login",
    "/texting",
];

/**
 * Дорогие и бесконечные разделы. Поиск идёт по 12 млн символов; у калькулятора
 * адресное пространство бесконечно (любая дата — свой адрес), и обходчик способен
 * ходить по нему годами, не находя ничего нового. Внутренние страницы этих
 * разделов и так не в карте сайта — здесь мы говорим об этом вслух.
 */
const EXPENSIVE = [
    "/search",
    "/dictionary?",
    "/dictionary/*/declension",
    "/calculator/",
];

/** Ручки API: их читают программы по ключу, в выдаче им делать нечего. */
const MACHINE = [
    "/api/",   // со слешем: страница описания /api остаётся открытой
    "/calendar.ics",
    "/offline",
];

const DISALLOW = [...PRIVATE, ...EXPENSIVE, ...MACHINE];

/**
 * Обходчики, которые собирают корпуса для обучения и ничего не приводят взамен:
 * ни читателя, ни ссылки. Корпус под CC BY 4.0, и против его распространения мы
 * не возражаем — возражаем против выкачки сайта постранично вместо API, за
 * которым для того же самого есть ключ и понятная квота.
 *
 * Список именно из «обучающих» имён. Те же компании ходят и по запросу
 * пользователя (ChatGPT-User, Perplexity-User, Claude-User) — эти оставлены,
 * потому что за ними стоит живой человек со ссылкой на источник.
 */
const HARVESTERS = [
    "GPTBot",
    "ClaudeBot",
    "anthropic-ai",
    "CCBot",
    "Google-Extended",
    "Applebot-Extended",
    "meta-externalagent",
    "FacebookBot",
    "Bytespider",
    "Amazonbot",
    "Diffbot",
    "Omgilibot",
    "ImagesiftBot",
    "PetalBot",
];

export default function robots(): MetadataRoute.Robots {
    return {
        rules: [
            {
                userAgent: "*",
                allow: "/",
                disallow: DISALLOW,
                // Google и Яндекс это правило не читают (у Яндекса частота обхода
                // задаётся в Вебмастере), но Bing, Mail.ru и мелкие обходчики —
                // читают, а именно они и приходят пачкой.
                crawlDelay: 2,
            },
            {
                userAgent: HARVESTERS,
                disallow: "/",
            },
        ],
        sitemap: `${BASE_URL}/sitemap.xml`,
    };
}

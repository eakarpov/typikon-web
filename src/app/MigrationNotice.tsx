'use client';

import { useEffect, useState } from "react";
import { isLegacyHost, LEGACY_SHUTDOWN_LABEL, SITE_HOST, SITE_URL } from "@/utils/site";

// Полоса о переезде — для того, кто пришёл на старый адрес. Временное: снимается
// вместе с остальным переездным после отключения старого домена.
//
// КЛИЕНТСКИЙ КОМПОНЕНТ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ. Хост запроса на сервере берётся
// из заголовков, а всякое обращение к ним в корневом макете делает динамической
// КАЖДУЮ страницу сайта — ровно то, от чего мы уходили, вынося сессию из
// рендера (см. «Блок 2» в ROADMAP: 19 пререндеренных маршрутов вместо двух).
// Ради полосы на три месяца платить возвратом к динамике всего сайта нельзя.
// Браузер же знает свой адрес и без сервера.
//
// Отсюда и мигание: до первой отрисовки у клиента адреса нет, поэтому полоса
// появляется мгновением позже страницы. Для полосы это не беда — в отличие от
// кнопки «Войти», из-за которой в своё время и завели признак isResolved.
//
// Показывается и тем, кто установил сайт приложением: у установленного PWA
// источник прежний, и переставить его можно только переустановкой.
const MigrationNotice = () => {
    const [legacy, setLegacy] = useState(false);

    useEffect(() => {
        setLegacy(isLegacyHost(window.location.hostname));
    }, []);

    if (!legacy) return null;

    return (
        <div className="bg-amber-100 border-b border-amber-300 px-3 py-2 text-sm font-serif">
            <b>Сайт переехал на {SITE_HOST}.</b>{" "}
            Этот адрес отключается {LEGACY_SHUTDOWN_LABEL} — обновите закладки.{" "}
            <a
                href={`${SITE_URL}${typeof window === "undefined" ? "" : window.location.pathname}`}
                className="text-amber-900 underline underline-offset-4"
            >
                Перейти на новый адрес
            </a>
            . Если сайт установлен приложением, поставьте его заново с нового адреса;
            подписки на календарь нужно оформить повторно.
        </div>
    );
};

export default MigrationNotice;

# ВЫБОР ЦЕЛИ ВЫКЛАДКИ. Подключается (source) всеми release-скриптами первой строкой.
#
# Зачем. Доступы к серверу лежали в одном файле .env.release, и цель выкладки была
# ровно одна. Машин стало больше — новая с доступным Телеграмом рядом со старой, —
# и одного файла на всех мало: правка его перед каждой выкладкой означает, что
# однажды его забудут поправить, и корпус уедет не туда, причём молча.
#
# Теперь файл на цель: .env.release.prod, .env.release.test и сколько угодно ещё.
# Цель называется ключом:
#
#     npm run release                       # prod, как и было
#     npm run release -- --target test      # то же на испытательную машину
#     TARGET=test npm run release:db        # то же переменной окружения
#     TARGET=test npm run release:db -- bible_verses
#
# Ключ — любое слово, под которое заведён файл: prod и test не перечислены
# нигде, кроме этого примечания. Проверяется не имя, а наличие файла — так
# опечатка (`--target tset`) останавливает выкладку, а не уводит её на прежний
# сервер по умолчанию.
#
# ПО УМОЛЧАНИЮ — PROD, и это не оплошность: без умолчания сломались бы привычные
# `npm run release:*`, а вместе с ними и мышечная память. Защитой служит не
# умолчание, а объявление: ниже печатается строка с ключом и хостом, и ни одна
# выкладка не проходит молча.

# ГДЕ ЛЕЖАТ СКРИПТЫ И ОТКУДА ОНИ РАБОТАЮТ — это два разных места, и путать их
# нельзя.
#
# Лежат они в scripts/, а работают ИЗ КОРНЯ ПРОЕКТА: почти всё, к чему они
# обращаются, лежит именно там — .env.production, .env.release.<ключ>, nobles.db,
# выгрузка корпуса, package.json. Поэтому ниже переход в корень, а путь к самим
# скриптам остаётся в RELEASE_DIR: им пользуются те места, где один скрипт зовёт
# другого (release-ustav.sh) или скармливает его серверу (`ssh bash -s < …`).
#
# Раньше и то и другое было корнем, и разницы не было видно. Теперь видно, и
# ценой одной строки: `cd` сюда возвращает прежнее поведение всем скриптам разом,
# так что относительные пути внутри них править не пришлось.
RELEASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$RELEASE_DIR/.." || exit 1
export RELEASE_DIR

# --- Ключ: из аргументов, иначе из окружения, иначе prod -----------------------
#
# Аргументы разбираются здесь и ЗДЕСЬ ЖЕ снимаются: release-db.sh принимает
# список частей, release-app.sh — версию и путь к apk, и ключ в их собственном
# разборе был бы лишним. `set --` в подключённом файле меняет аргументы
# подключившего — на этом всё и держится.
_rt_rest=()
while [ $# -gt 0 ]; do
    case "$1" in
        --target=*) TARGET="${1#--target=}" ;;
        --target|-t)
            if [ $# -lt 2 ]; then
                echo "у --target нет значения: --target prod | --target test" >&2
                exit 1
            fi
            TARGET="$2"; shift ;;
        *)          _rt_rest+=("$1") ;;
    esac
    shift
done
# Форма с ${...+...} — ради `set -u` в release-app.sh: в bash до 4.4 пустой
# массив под `set -u` считается неустановленной переменной, и скрипт падал бы
# на выкладке без аргументов.
set -- ${_rt_rest[@]+"${_rt_rest[@]}"}
unset _rt_rest

TARGET=${TARGET:-prod}
# Наружу — чтобы вложенные вызовы (release-ustav.sh зовёт два скрипта) шли туда
# же, куда и внешний, без передачи ключа руками.
export TARGET

# --- Файл доступов -------------------------------------------------------------
RELEASE_ENV=".env.release.$TARGET"

if [ ! -f "$RELEASE_ENV" ]; then
    # Переходная поблажка: пока .env.release.prod не заведён, prod берётся из
    # прежнего .env.release. Снять её можно будет, когда файл появится; до тех
    # пор старый файл работает как раньше, и ничего чинить перед выкладкой не
    # нужно. Для любого другого ключа поблажки нет: молча уехать на прод вместо
    # испытательной машины — ровно то, от чего всё это написано.
    if [ "$TARGET" = prod ] && [ -f .env.release ]; then
        RELEASE_ENV=.env.release
    else
        echo "нет $RELEASE_ENV — цель «$TARGET» не настроена." >&2
        echo >&2
        echo "Заведи файл по образцу .env.release.example:" >&2
        echo "    cp .env.release.example $RELEASE_ENV && \$EDITOR $RELEASE_ENV" >&2
        echo >&2
        echo "Настроенные цели:" >&2
        for f in .env.release.*; do
            case "$f" in
                .env.release.example|'.env.release.*') continue ;;
            esac
            echo "    ${f#.env.release.}" >&2
        done
        # Прежний файл — это и есть prod, пока поблажка не снята; не назвать его
        # здесь значило бы сказать, что настроенных целей нет вовсе.
        [ -f .env.release ] && echo "    prod (из .env.release)" >&2
        exit 1
    fi
fi

# Разбор тот же, каким он был во всех скриптах до сих пор, — нарочно: менять
# его заодно значило бы менять поведение на файлах, которые уже лежат у всех.
export $(grep -v '^#' "$RELEASE_ENV" | xargs)

for _rt_var in USERNAME HOST PASSWORD; do
    eval "[ -n \"\${$_rt_var:-}\" ]" || {
        echo "в $RELEASE_ENV нет $_rt_var" >&2
        exit 1
    }
done
unset _rt_var

# --- Что можно задать в файле цели ---------------------------------------------
#
# Всё ниже — со значениями по умолчанию, равными нынешнему проду: файл цели,
# в котором есть только USERNAME/HOST/PASSWORD, ведёт себя в точности как
# прежний .env.release.

# Каталог сайта на сервере. Отсюда выводятся остальные, чтобы при переезде
# правилась одна строка, а не пять.
REMOTE_ROOT=${REMOTE_ROOT:-/var/www/typikon.su/typikon-web}
# Служба сборки последования — РЯДОМ с сайтом, а не внутри: в каталоге сайта
# своё рабочее дерево git со своей сборкой.
ORDO_REMOTE=${ORDO_REMOTE:-$(dirname "$REMOTE_ROOT")/typikon-ordo}
# Выгрузка корпуса и сборки приложения лежат вне каталога сайта — там идут
# git pull и сборка, и git clean -fdx снёс бы их молча.
DUMP_REMOTE=${DUMP_REMOTE:-/var/www/typikon-data}
APP_REMOTE=${APP_REMOTE:-/var/www/typikon-app-releases}

# Какой местный файл окружения уезжает на сервер файлом .env.production.
# Испытательной машине нужны свои токены — свой бот, своё приложение VK, свой
# ключ рассылки, — иначе проверка на ней пойдёт от имени настоящего сайта.
# Имя НА СЕРВЕРЕ остаётся .env.production: другого Next не читает.
ENV_FILE=${ENV_FILE:-.env.production}

# Адрес цели снаружи: по нему сбрасывается кэш ответов устава после выкладки.
SITE_URL=${SITE_URL:-https://www.typikon.info}

export REMOTE_ROOT ORDO_REMOTE DUMP_REMOTE APP_REMOTE ENV_FILE SITE_URL

if [ ! -f "$ENV_FILE" ]; then
    echo "нет $ENV_FILE — его везут на сервер все release-скрипты" >&2
    exit 1
fi

# --- Общие приёмы --------------------------------------------------------------
#
# Молчащий ssh — то, обо что спотыкалась выкладка базы: пока mongorestore возится
# с индексами, в канале тишина, и сеанс закрывают как бездействующий. Keepalive
# шлёт пустое каждые полминуты и держит его живым. Здесь — для всех скриптов, а
# не для одного: тишина бывает и при распаковке 91 МБ корпуса.
SSH_OPTS=${SSH_OPTS:--o ServerAliveInterval=30 -o ServerAliveCountMax=10}

ssh_run() { sshpass -f <(printf '%s\n' "$PASSWORD") ssh $SSH_OPTS "$USERNAME@$HOST" "$@"; }
scp_put() { sshpass -f <(printf '%s\n' "$PASSWORD") scp $SSH_OPTS "$1" "$USERNAME@$HOST:$2"; }
scp_get() { sshpass -f <(printf '%s\n' "$PASSWORD") scp $SSH_OPTS "$USERNAME@$HOST:$1" "$2"; }

# Окружение везут все скрипты без исключения. Без этого выходит тихая ловушка:
# файл лежит там, где надо, а сайт про него не знает и честно сообщает, что
# раздел не выложен.
put_env() { scp_put "$ENV_FILE" "$REMOTE_ROOT/.env.production"; }

# Значение из файла окружения ЦЕЛИ. Нужно там, где скрипту важно то же, что и
# сайту: куда лечь корпусу (RULES_DB) и каким токеном сбросить кэш
# (REVALIDATE_TOKEN). Читаем из файла, а не из окружения оболочки: в окружении
# его нет, и до сих пор это молчало — сброс кэша устава уходил с пустым
# заголовком, ручка отвечала 404, а скрипт печатал её ответ как успех.
env_value() { grep -v '^#' "$ENV_FILE" | grep "^$1=" | head -1 | cut -d= -f2-; }

# ОБЪЯВЛЕНИЕ. Печатается всегда и до первого действия: единственная защита от
# выкладки не на ту машину — увиденная строка, а не угаданное умолчание.
# Код возврата ПОСЛЕДНЕЙ команды здесь — это код возврата `source` у
# подключившего, а у release-app.sh стоит `set -e`. Поэтому конец файла —
# полноценный if, а не `[ ... ] && echo`: несработавшее «и» вернуло бы единицу
# и остановило выкладку на пустом месте.
echo "── выкладка: $TARGET ($USERNAME@$HOST:$REMOTE_ROOT), окружение $ENV_FILE"
if [ "$RELEASE_ENV" = .env.release ]; then
    echo "   доступы из .env.release — переименуй в .env.release.prod, поблажка временная"
fi

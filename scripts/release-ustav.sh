# Выкладка правки устава — целиком и в правильном порядке.
#
# Зачем отдельная команда, если есть release:rules-db и release:ordo.
# Потому что правила устава живут на сервере В ДВУХ ВИДАХ, и это не дублирование:
#
#   * СКОМПИЛИРОВАННЫМИ — build_db.py разбирает rules/**.yaml в таблицы
#     ordo_steps, typikon_allocation и прочие, и сборка службы читает их, а не
#     файлы. Едут они внутри корпуса (release:rules-db);
#   * ФАЙЛАМИ — их текст показывает «лестница правил», объясняющая выдачу.
#     Едут со службой (release:ordo).
#
# Выложить одно без другого — значит получить страницу, где показанное правило
# не соответствует собранной службе. Разойтись они могут молча, и заметить это
# тяжело: обе половины выглядят исправными.
#
# Порядок важен: сперва корпус, потом служба. Служба при запуске читает корпус,
# и поднимать её на старом, пока новый ещё едет, незачем.
#
# Цель — ключом (release-target.sh). Подключаем его и здесь, хотя сам этот
# скрипт по ssh не ходит: он снимает ключ с аргументов и выставляет TARGET в
# окружение, откуда оба вызываемых скрипта его и возьмут. Без этого пришлось бы
# передавать ключ каждому из них руками, и однажды передали бы не всем.
#
#     npm run release:ustav -- --target test

set -e
. "$(dirname "$0")/release-target.sh"

RULES_SRC=${RULES_SRC:-../typikon-rules}
DB="$RULES_SRC/src/data.db"

if [ ! -f "$DB" ]; then
    echo "нет $DB — собери корпус: cd $RULES_SRC && python3 src/build_db.py"
    exit 1
fi

# Правила правились после пересборки? Тогда в базе лежит ПРЕЖНИЙ устав, и
# выложится он же — при том что «лестница» покажет новые файлы. Это ровно то
# расхождение, ради которого написана эта команда, и ловим мы его здесь.
STALE=$(find "$RULES_SRC/rules" "$RULES_SRC/parsed" -newer "$DB" -name '*.yaml' -print -quit 2>/dev/null || true)
if [ -n "$STALE" ]; then
    echo "правила новее корпуса — например:"
    echo "    $STALE"
    echo "пересобери базу и повтори: cd $RULES_SRC && python3 src/build_db.py"
    exit 1
fi

echo "== корпус (в нём же скомпилированный устав)"
bash "$RELEASE_DIR/rules-db-release.sh"

echo
echo "== служба сборки (код и сами файлы правил)"
bash "$RELEASE_DIR/release-ordo.sh"
